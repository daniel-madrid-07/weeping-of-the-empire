// Software binary64 for GPUs without shaderFloat64 (Intel Arc; present's any-PC audit, 2026-10-27). The translator emits
// these on uint64_t bit patterns instead of `double` when maxwell_soft_f64 is set (translate.c: DADD / DMUL / DFMA /
// F2F.F64), so the 'material' vertex shaders that compute positions in double precision still build, with IEEE results:
// add, mul, f32 <-> f64 and the integer roundings are bit-exact round-to-nearest-even (Berkeley SoftFloat 3e's
// algorithms, BSD-3-Clause: s_addMagsF64, s_subMagsF64, f64_mul, f32_to_f64, f64_to_f32, f64_roundToInt, s_roundPackToF64,
// s_normRoundPackToF64, s_roundPackToF32). DFMA is mul then add (two roundings, not fused): at most 1 ulp of a double
// apart, gone in the F2F.F32 that ends these shaders. NaNs come out quiet, the first NaN operand's payload.
// The text is GLSL and C at once: translate.c defines U64 / U32 / I32 as constructors, test_soft_f64.py (next to this file) as
// casts and compiles it on the host against native doubles (the test of this exact text).
#pragma once
static const char soft_f64_glsl[] =
    "uint sf_clz64(uint64_t a) { uint hi = U32(a >> 32); return hi != 0u ? U32(31 - findMSB(hi)) : U32(63 - findMSB(U32(a))); }\n"
    "uint64_t sf_jam(uint64_t a, uint d) { return d < 63u ? ((a >> d) | (((a << ((64u - d) & 63u)) != 0ul) ? 1ul : 0ul)) : (a != 0ul ? 1ul : 0ul); }\n"
    "uint64_t sf_pack(uint s, int e, uint64_t sig) { return (U64(s) << 63) + (U64(e) << 52) + sig; }\n"
    "bool sf_isnan(uint64_t a) { return ((a >> 52) & 0x7FFul) == 0x7FFul && (a & 0xFFFFFFFFFFFFFul) != 0ul; }\n"
    "uint64_t sf_nan(uint64_t a, uint64_t b) { return (sf_isnan(a) ? a : sf_isnan(b) ? b : 0xFFF8000000000000ul) | 0x8000000000000ul; }\n"
    "uint64_t sf_round_pack(uint s, int e, uint64_t sig) {\n"
    "    uint rb = U32(sig & 0x3FFul);\n"
    "    if (e < 0 || e >= 0x7FD) {\n"
    "        if (e < 0) { sig = sf_jam(sig, U32(-e)); e = 0; rb = U32(sig & 0x3FFul); }\n"
    "        else if (e > 0x7FD || sig + 0x200ul >= 0x8000000000000000ul) return sf_pack(s, 0x7FF, 0ul);\n"
    "    }\n"
    "    sig = (sig + 0x200ul) >> 10;\n"
    "    if (rb == 0x200u) sig &= ~1ul;\n"
    "    if (sig == 0ul) e = 0;\n"
    "    return sf_pack(s, e, sig);\n"
    "}\n"
    "uint64_t sf_norm_round_pack(uint s, int e, uint64_t sig) {\n"
    "    int sh = I32(sf_clz64(sig)) - 1;\n"
    "    e -= sh;\n"
    "    if (sh >= 10 && e >= 0 && e < 0x7FD) return sf_pack(s, sig != 0ul ? e : 0, sig << U32(sh - 10));\n"
    "    return sf_round_pack(s, e, sig << U32(sh));\n"
    "}\n"
    "uint64_t sf_add_mags(uint64_t a, uint64_t b, uint s) {\n"
    "    int ea = I32((a >> 52) & 0x7FFul), eb = I32((b >> 52) & 0x7FFul);\n"
    "    uint64_t ma = a & 0xFFFFFFFFFFFFFul, mb = b & 0xFFFFFFFFFFFFFul, mz;\n"
    "    int d = ea - eb, ez;\n"
    "    if (d == 0) {\n"
    "        if (ea == 0) return a + mb;\n"
    "        if (ea == 0x7FF) return (ma | mb) != 0ul ? sf_nan(a, b) : a;\n"
    "        ez = ea;\n"
    "        mz = (0x20000000000000ul + ma + mb) << 9;\n"
    "    } else {\n"
    "        ma <<= 9;\n"
    "        mb <<= 9;\n"
    "        if (d < 0) {\n"
    "            if (eb == 0x7FF) return mb != 0ul ? sf_nan(a, b) : sf_pack(s, 0x7FF, 0ul);\n"
    "            ez = eb;\n"
    "            ma = ea != 0 ? ma + 0x2000000000000000ul : ma << 1;\n"
    "            ma = sf_jam(ma, U32(-d));\n"
    "        } else {\n"
    "            if (ea == 0x7FF) return ma != 0ul ? sf_nan(a, b) : a;\n"
    "            ez = ea;\n"
    "            mb = eb != 0 ? mb + 0x2000000000000000ul : mb << 1;\n"
    "            mb = sf_jam(mb, U32(d));\n"
    "        }\n"
    "        mz = 0x2000000000000000ul + ma + mb;\n"
    "        if (mz < 0x4000000000000000ul) { ez--; mz <<= 1; }\n"
    "    }\n"
    "    return sf_round_pack(s, ez, mz);\n"
    "}\n"
    "uint64_t sf_sub_mags(uint64_t a, uint64_t b, uint s) {\n"
    "    int ea = I32((a >> 52) & 0x7FFul), eb = I32((b >> 52) & 0x7FFul);\n"
    "    uint64_t ma = a & 0xFFFFFFFFFFFFFul, mb = b & 0xFFFFFFFFFFFFFul, mz;\n"
    "    int d = ea - eb, ez;\n"
    "    if (d == 0) {\n"
    "        if (ea == 0x7FF) return (ma | mb) != 0ul ? sf_nan(a, b) : 0xFFF8000000000000ul;\n"
    "        if (ma == mb) return 0ul;\n"
    "        if (ea != 0) ea--;\n"
    "        uint64_t md = ma - mb;\n"
    "        if (mb > ma) { s ^= 1u; md = mb - ma; }\n"
    "        int sh = I32(sf_clz64(md)) - 11;\n"
    "        ez = ea - sh;\n"
    "        if (ez < 0) { sh = ea; ez = 0; }\n"
    "        return sf_pack(s, ez, md << U32(sh));\n"
    "    }\n"
    "    ma <<= 10;\n"
    "    mb <<= 10;\n"
    "    if (d < 0) {\n"
    "        s ^= 1u;\n"
    "        if (eb == 0x7FF) return mb != 0ul ? sf_nan(a, b) : sf_pack(s, 0x7FF, 0ul);\n"
    "        ma += ea != 0 ? 0x4000000000000000ul : ma;\n"
    "        ma = sf_jam(ma, U32(-d));\n"
    "        mb |= 0x4000000000000000ul;\n"
    "        ez = eb;\n"
    "        mz = mb - ma;\n"
    "    } else {\n"
    "        if (ea == 0x7FF) return ma != 0ul ? sf_nan(a, b) : a;\n"
    "        mb += eb != 0 ? 0x4000000000000000ul : mb;\n"
    "        mb = sf_jam(mb, U32(d));\n"
    "        ma |= 0x4000000000000000ul;\n"
    "        ez = ea;\n"
    "        mz = ma - mb;\n"
    "    }\n"
    "    return sf_norm_round_pack(s, ez - 1, mz);\n"
    "}\n"
    "uint64_t sf_add(uint64_t a, uint64_t b) { uint s = U32(a >> 63); return s == U32(b >> 63) ? sf_add_mags(a, b, s) : sf_sub_mags(a, b, s); }\n"
    "uint64_t sf_mul_hi_jam(uint64_t a, uint64_t b) {\n"
    "    uint64_t al = a & 0xFFFFFFFFul, ah = a >> 32, bl = b & 0xFFFFFFFFul, bh = b >> 32;\n"
    "    uint64_t p0 = al * bl, p1 = al * bh, p2 = ah * bl, p3 = ah * bh;\n"
    "    uint64_t mid = p1 + p2, carry = mid < p1 ? 0x100000000ul : 0ul;\n"
    "    uint64_t lo = p0 + (mid << 32);\n"
    "    uint64_t hi = p3 + (mid >> 32) + carry + (lo < p0 ? 1ul : 0ul);\n"
    "    return hi | (lo != 0ul ? 1ul : 0ul);\n"
    "}\n"
    "uint64_t sf_mul(uint64_t a, uint64_t b) {\n"
    "    uint s = U32((a ^ b) >> 63);\n"
    "    int ea = I32((a >> 52) & 0x7FFul), eb = I32((b >> 52) & 0x7FFul);\n"
    "    uint64_t ma = a & 0xFFFFFFFFFFFFFul, mb = b & 0xFFFFFFFFFFFFFul;\n"
    "    if (ea == 0x7FF || eb == 0x7FF) {\n"
    "        if (sf_isnan(a) || sf_isnan(b)) return sf_nan(a, b);\n"
    "        return ((ea == 0x7FF ? b : a) << 1) == 0ul ? 0xFFF8000000000000ul : sf_pack(s, 0x7FF, 0ul);\n"
    "    }\n"
    "    if (ea == 0) { if (ma == 0ul) return sf_pack(s, 0, 0ul); int sh = I32(sf_clz64(ma)) - 11; ea = 1 - sh; ma <<= U32(sh); }\n"
    "    if (eb == 0) { if (mb == 0ul) return sf_pack(s, 0, 0ul); int sh = I32(sf_clz64(mb)) - 11; eb = 1 - sh; mb <<= U32(sh); }\n"
    "    int ez = ea + eb - 0x3FF;\n"
    "    ma = (ma | 0x10000000000000ul) << 10;\n"
    "    mb = (mb | 0x10000000000000ul) << 11;\n"
    "    uint64_t mz = sf_mul_hi_jam(ma, mb);\n"
    "    if (mz < 0x4000000000000000ul) { ez--; mz <<= 1; }\n"
    "    return sf_round_pack(s, ez, mz);\n"
    "}\n"
    "uint64_t sf_from_f32(uint x) {\n"
    "    uint s = x >> 31, f = x & 0x7FFFFFu;\n"
    "    int e = I32((x >> 23) & 0xFFu);\n"
    "    if (e == 0xFF) return f != 0u ? (sf_pack(s, 0x7FF, 0ul) | 0x8000000000000ul | (U64(f) << 29)) : sf_pack(s, 0x7FF, 0ul);\n"
    "    if (e == 0) {\n"
    "        if (f == 0u) return sf_pack(s, 0, 0ul);\n"
    "        int sh = (31 - findMSB(f)) - 8;\n"
    "        e = 1 - sh - 1;\n"
    "        f <<= U32(sh);\n"
    "    }\n"
    "    return sf_pack(s, e + 0x380, U64(f) << 29);\n"
    "}\n"
    "uint sf_round_pack32(uint s, int e, uint sig) {\n"
    "    uint rb = sig & 0x7Fu;\n"
    "    if (e < 0 || e >= 0xFD) {\n"
    "        if (e < 0) {\n"
    "            uint d = U32(-e);\n"
    "            sig = d < 31u ? ((sig >> d) | (((sig << ((32u - d) & 31u)) != 0u) ? 1u : 0u)) : (sig != 0u ? 1u : 0u);\n"
    "            e = 0;\n"
    "            rb = sig & 0x7Fu;\n"
    "        } else if (e > 0xFD || sig + 0x40u >= 0x80000000u) return (s << 31) | 0x7F800000u;\n"
    "    }\n"
    "    sig = (sig + 0x40u) >> 7;\n"
    "    if (rb == 0x40u) sig &= ~1u;\n"
    "    if (sig == 0u) e = 0;\n"
    "    return (s << 31) + (U32(e) << 23) + sig;\n"
    "}\n"
    "uint sf_to_f32(uint64_t a) {\n"
    "    uint s = U32(a >> 63);\n"
    "    int e = I32((a >> 52) & 0x7FFul);\n"
    "    uint64_t f = a & 0xFFFFFFFFFFFFFul;\n"
    "    if (e == 0x7FF) return f != 0ul ? ((s << 31) | 0x7FC00000u | U32(f >> 29)) : ((s << 31) | 0x7F800000u);\n"
    "    uint f32 = U32(f >> 22) | ((f & 0x3FFFFFul) != 0ul ? 1u : 0u);\n"
    "    if ((U32(e) | f32) == 0u) return s << 31;\n"
    "    return sf_round_pack32(s, e - 0x381, f32 | 0x40000000u);\n"
    "}\n"
    "uint64_t sf_round_int(uint64_t a, int mode) {\n"   // (mode 0 nearest even, 1 floor, 2 ceil, 3 trunc)
    "    int e = I32((a >> 52) & 0x7FFul);\n"
    "    if (e <= 0x3FE) {\n"
    "        if ((a << 1) == 0ul) return a;\n"
    "        uint64_t z = a & 0x8000000000000000ul;\n"
    "        if (mode == 0) { if (e == 0x3FE && (a & 0xFFFFFFFFFFFFFul) != 0ul) z |= 0x3FF0000000000000ul; }\n"
    "        else if (mode == 1) { if (z != 0ul) z = 0xBFF0000000000000ul; }\n"
    "        else if (mode == 2) { if (z == 0ul) z = 0x3FF0000000000000ul; }\n"
    "        return z;\n"
    "    }\n"
    "    if (e >= 0x433) return sf_isnan(a) ? (a | 0x8000000000000ul) : a;\n"
    "    uint64_t last = 1ul << U32(0x433 - e), mask = last - 1ul, z = a;\n"
    "    if (mode == 0) { z += last >> 1; if ((z & mask) == 0ul) z &= ~last; }\n"
    "    else if ((mode == 1 && (a >> 63) != 0ul) || (mode == 2 && (a >> 63) == 0ul)) z += mask;\n"
    "    return z & ~mask;\n"
    "}\n"
    "uint64_t sf_sat(uint64_t a) { return ((a >> 63) != 0ul || sf_isnan(a)) ? 0ul : a >= 0x3FF0000000000000ul ? 0x3FF0000000000000ul : a; }\n";

"""TotK code patches applied to a module image before recompilation.

    python -m games.totk.patches apply --image <main.img | exefs/main> --out <main.patched.img> [--features default]
    python -m games.totk.patches list
    python -m games.totk.patches generate [--image I]   # sites_v100.py -> v100.toml
    python -m games.totk.patches check [--image I]      # v100.toml == what sites_v100.py generates

The table (v100.toml) lists every word: module, offset, the new bytes (or `copy_of`: a word of the image itself, moved
into a veneer), the new word's disassembly, reason, feature. It holds no word of the game: each feature has the SHA-256
of every image word it replaces or copies (`original_sha256`), so `apply` checks the image (the 1.0.0 main it was made
for, then every selected feature's words) before writing any; a mismatch refuses the whole image instead of
half-patching it. generate and check read those words from the user's own image (--image, default: the work folder's).
Next to the output apply writes <out>.patches.json: what was applied, and the data page the runtime must commit (see
README.md, "Interfaces")."""
import glob
import hashlib
import json
import os
import struct
import tomllib
from pathlib import Path

from . import sites_v100

HERE = Path(__file__).resolve().parent
TABLE_V100 = HERE / 'v100.toml'

TITLE_ID = '0100F2C0115B6000'
VERSION = '1.0.0'
# 1.0.0 main, as the NSO and as the flat image the NSO loader (recomp/nso.py, pipeline/modules.py) makes of it.
MAIN_NSO_SHA256 = 'faf81f8a609ff61a6322d04948132b5929af9f6e2398e0e0ebbe819b8ba3eaab'
MAIN_IMAGE_SHA256 = 'a095f9114edad2f9e77a6a217143eaccf7a4b25ab8273792d327774b4652d230'
MAIN_BUILD_ID = '082ce09b06e33a123cb1e2770f5f9147709033db'
MAIN_SPAN = 0x4666000          # loaded size, .bss included, page aligned (layout.json "span")
DATA_PAGE_OFFSET = (MAIN_SPAN + 0x3fff) & ~0x3fff
DEFAULT_FEATURES = tuple(name for name, (_, on, _) in sites_v100.FEATURES.items() if on)


class PatchError(Exception):
    pass


def layout_v100():
    return sites_v100.Layout(text_end=sites_v100.TEXT_END_V100, data_off=DATA_PAGE_OFFSET)


# ---------------------------------------------------------------------------------------------------------- the table

def _disasm(word, offset):
    try:
        from capstone import Cs, CS_ARCH_ARM64, CS_MODE_ARM
    except ImportError:     # the table stays valid without it; the disassembly columns are documentation
        return '?'
    md = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
    for ins in md.disasm(struct.pack('<I', word), offset):
        return f'{ins.mnemonic} {ins.op_str}'.strip()
    return '(not an instruction)' if word else '(zero padding)'


def _hexbytes(word):
    return struct.pack('<I', word).hex()


def feature_digest(image, offsets):
    """SHA-256 of the image's words at `offsets` (each as its 8-byte little-endian offset, then the 4 bytes)."""
    h = hashlib.sha256()
    for off in sorted(set(offsets)):
        h.update(struct.pack('<Q', off) + bytes(image[off:off + 4]))
    return h.hexdigest()


def _checked(words):
    """The offsets a feature's words read from the image: each word's own (replaced, or padding) and each copy's."""
    return [w.offset for w in words] + [w.new.offset for w in words if isinstance(w.new, sites_v100.Orig)]


def default_image():
    """The flat 1.0.0 main image of the work folder (tools/engine/build.py's <work>/engine/img/<id>/main.bin)."""
    builder = Path(__file__).resolve().parents[3].parent / 'build-work'   # (tools/builder's work folder)
    works = [os.environ.get('NXRECOMP_WORK'), str(builder), r'C:\nxrecomp-work']   # (build.py's default)
    for work in filter(None, works):
        for path in sorted(glob.glob(os.path.join(work, 'engine', 'img', '*', 'main.bin'))):
            if '-p' not in os.path.basename(os.path.dirname(path)):    # (<id>-p<patches>: already patched)
                return Path(path)
    raise PatchError(f'no unpatched main.bin under <work>/engine/img ({", ".join(filter(None, works))}): pass --image')


def game_v100(lay=None):
    """The [game] section of v100.toml: what `load_main_image` checks an image against."""
    lay = lay or layout_v100()
    return dict(title_id=TITLE_ID, version=VERSION, build_id=MAIN_BUILD_ID, nso_sha256=MAIN_NSO_SHA256,
                image_sha256=MAIN_IMAGE_SHA256, text_end=lay.text_end, span=MAIN_SPAN, data_page=lay.data_off)


def generate_toml(image, lay=None):
    """The v100.toml text for every feature (apply selects among them); image: the flat 1.0.0 main (load_main_image)."""
    lay = lay or layout_v100()
    return table_toml(game_v100(lay), sites_v100.build(lay, list(sites_v100.FEATURES)), [
        '# TotK 1.0.0 code patches. GENERATED by `python -m games.totk.patches generate` from sites_v100.py: edit that',
        '# file, not this one (`check` compares the two). Bytes are little-endian, as in memory; offsets are main offsets.',
        '# Each [[patch]] is one 4-byte word, new (ours) or copy_of (the image\'s own word at that offset). apply refuses',
        '# the image unless the SHA-256 of every selected feature\'s replaced and copied words is its original_sha256.'],
        image)


def table_toml(game, patches, header, image, features=None):
    """A patch table: `game` (title_id, version, build_id, nso_sha256, image_sha256, text_end, span, data_page), the
    feature list (default: sites_v100.FEATURES) with each feature's original_sha256 over `image` (the flat main of that
    build), and every word of `patches`. A Word with `v100_offset` (games.totk.patches.port) records where the 1.0.0
    table has it."""
    out = header + ['',
           '[game]',
           f'title_id = "{game["title_id"]}"',
           f'version = "{game["version"]}"',
           'module = "main"',
           f'build_id = "{game["build_id"]}"',
           f'nso_sha256 = "{game["nso_sha256"]}"',
           f'image_sha256 = "{game["image_sha256"]}"',
           f'text_end = {game["text_end"]:#x}',
           f'span = {game["span"]:#x}',
           f'data_page = {game["data_page"]:#x}',
           f'data_page_size = {sites_v100.DATA_PAGE_SIZE:#x}',
           '']
    words = {}
    for p in patches:
        words.setdefault(p.feature, []).extend(_checked(p.words))
    for name, (_, on, needs) in (features or sites_v100.FEATURES).items():
        out += ['[[feature]]', f'name = "{name}"', f'default = {"true" if on else "false"}',
                'needs = [' + ', '.join(f'"{n}"' for n in needs) + ']',
                f'original_sha256 = "{feature_digest(image, words.get(name, []))}"', '']
    for p in patches:
        for start, end in p.veneers:
            out += ['[[veneer]]', f'feature = "{p.feature}"', 'module = "main"', f'start = {start:#x}',
                    f'end = {end:#x}', '']
        for w in p.words:
            if isinstance(w.new, sites_v100.Orig):
                new = [f'copy_of = {w.new.offset:#x}', f'new_asm = "(the word at main+{w.new.offset:#x})"']
            else:
                new = [f'new = "{_hexbytes(w.new)}"', f'new_asm = "{_disasm(w.new, w.offset)}"']
            out += ['[[patch]]', f'feature = "{p.feature}"', 'module = "main"', f'offset = {w.offset:#x}', *new,
                    'reason = ' + json.dumps(w.reason), '']
            if getattr(w, 'v100_offset', None) is not None:
                out.insert(len(out) - 1, f'v100_offset = {w.v100_offset:#x}')
    return '\n'.join(out)


def read_table(path=TABLE_V100, image=None):
    """The table; with the image (the flat 1.0.0 main) every row also gets `original` (the image's word) and a copy row
    its `new`, after every feature's original_sha256 was checked (resolve)."""
    with open(path, 'rb') as f:
        t = tomllib.load(f)
    for p in t['patch']:
        p['new'] = bytes.fromhex(p['new']) if 'new' in p else None
        p['original'] = None
        if p['new'] is not None and len(p['new']) != 4:
            raise PatchError(f'{path}: main+{p["offset"]:#x}: a word is 4 bytes')
    if image is not None:
        resolve(t, image)
    return t


def resolve(table, image, features=None):
    """Check each feature's words in `image` against its original_sha256 (all features, or `features`), then fill in
    `original` (the image's word) and the copies' `new`. Raises PatchError naming the features that differ."""
    rows = {}
    for p in table['patch']:
        rows.setdefault(p['feature'], []).append(p)
    bad = []
    for f in table['feature']:
        if features is not None and f['name'] not in features:
            continue
        mine = rows.get(f['name'], [])
        offs = [p['offset'] for p in mine] + [p['copy_of'] for p in mine if 'copy_of' in p]
        if max(offs, default=0) + 4 > len(image):
            bad.append(f'{f["name"]} (outside the image)')
        elif feature_digest(image, offs) != f['original_sha256']:
            bad.append(f['name'])
    if bad:
        raise PatchError('the image differs from the table build where these features patch, nothing written: '
                         + ', '.join(bad) + ' (python -m games.totk.patches diff --image <it> --reference <that build> '
                         'lists the words)')
    for f in table['feature']:
        if features is not None and f['name'] not in features:
            continue
        for p in rows.get(f['name'], []):
            p['original'] = bytes(image[p['offset']:p['offset'] + 4])
            if 'copy_of' in p:
                p['new'] = bytes(image[p['copy_of']:p['copy_of'] + 4])
    return table


def resolve_features(spec, table):
    """'default', 'all', 'none' or a comma list (each name may be prefixed with '-' to drop it from what came before)."""
    known = {f['name']: f for f in table['feature']}
    chosen = []
    for item in [s.strip() for s in (spec or 'default').split(',') if s.strip()]:
        if item in ('default', 'all', 'none'):
            chosen = [] if item == 'none' else [n for n, f in known.items() if item == 'all' or f['default']]
        elif item.startswith('-'):
            if item[1:] not in known:
                raise PatchError(f'unknown feature {item[1:]} (known: {", ".join(known)})')
            chosen = [n for n in chosen if n != item[1:]]
        elif item in known:
            chosen = chosen + [item] if item not in chosen else chosen
        else:
            raise PatchError(f'unknown feature {item} (known: {", ".join(known)})')
    for n in chosen:
        missing = [d for d in known[n]['needs'] if d not in chosen]
        if missing:
            raise PatchError(f'feature {n} needs {", ".join(missing)}')
    return [n for n in known if n in chosen]


# ---------------------------------------------------------------------------------------------------------- images

def load_main_image(path, game=None):
    """The flat main image from an NSO (decoded by recomp/nso.py, the loader) or a flat image (<work>/images/main.img),
    for the build a table's [game] names (default 1.0.0). Refuses anything else: the table's offsets are for that
    exact build."""
    g = game or game_v100()
    raw = Path(path).read_bytes()
    if raw[:4] == b'NSO0':
        if hashlib.sha256(raw).hexdigest() != g['nso_sha256']:
            raise PatchError(f'{path}: not the {g["version"]} main NSO (SHA-256 {hashlib.sha256(raw).hexdigest()})')
        from recomp.nso import load_nso
        m = load_nso(str(path), 'main')
        if m.text.end != g['text_end'] or m.build_id.hex()[:40] != g['build_id']:
            raise PatchError(f'{path}: text end {m.text.end:#x} / build id {m.build_id.hex()} unexpected')
        raw = m.data
    if hashlib.sha256(raw).hexdigest() != g['image_sha256']:
        raise PatchError(f'{path}: not the {g["version"]} main image (SHA-256 {hashlib.sha256(raw).hexdigest()}); '
                         f'expected {g["image_sha256"]}')
    return bytearray(raw)


def apply(image, table, features):
    """Patch `image` (bytearray, the flat 1.0.0 main) in place. Returns the report dict. Raises PatchError (and leaves
    the image untouched) when any selected original word does not match."""
    g = table['game']
    rows = [p for p in table['patch'] if p['feature'] in features]
    resolve(table, image, features)   # (before any write: copies read the unpatched words)
    mismatches = []
    seen = {}
    for p in rows:
        off, n = p['offset'], len(p['original'])
        if p['module'] != 'main':
            raise PatchError(f'{p["module"]}: only main is patched')
        if off + n > len(image):
            mismatches.append(dict(offset=hex(off), feature=p['feature'], problem='outside the image'))
            continue
        if off < g['text_end'] <= off + n - 1 or (off >= g['text_end'] and off + n > ((g['text_end'] + 0xfff) & ~0xfff)):
            mismatches.append(dict(offset=hex(off), feature=p['feature'], problem='veneer outside the text padding'))
        if off in seen and seen[off] != p['feature']:
            mismatches.append(dict(offset=hex(off), feature=p['feature'], problem=f'also patched by {seen[off]}'))
        seen[off] = p['feature']
        have = bytes(image[off:off + n])
        if have != p['original']:
            mismatches.append(dict(offset=hex(off), feature=p['feature'], problem='changed while patching'))
    if mismatches:
        raise PatchError('original bytes do not match, nothing written: ' + json.dumps(mismatches))
    for p in rows:
        image[p['offset']:p['offset'] + len(p['new'])] = p['new']
    veneers = [v for v in table.get('veneer', []) if v['feature'] in features]
    code_end = max([g['text_end']] + [v['end'] for v in veneers])
    per = {f: sum(1 for p in rows if p['feature'] == f) for f in features}
    return dict(
        status='pass', game=dict(title_id=g['title_id'], version=g['version'], build_id=g['build_id']),
        features=features, words=per, words_total=len(rows),
        changed_words=sum(1 for p in rows if p['original'] != p['new']),
        text_end=hex(g['text_end']), text_end_patched=hex(code_end),
        veneers=[dict(feature=v['feature'], start=hex(v['start']), end=hex(v['end'])) for v in veneers],
        data_page=dict(module='main', offset=hex(g['data_page']), size=hex(g['data_page_size']),
                       header='games/totk/include/totk/data_page.h'),
        uses_data_page=any(f not in ('fps60', 'highfps') for f in features),
        image_sha256=hashlib.sha256(image).hexdigest())

"""lock_wheels.py: tools/builder/wheels-setup.txt and wheels-venv.txt, the hash-pinned Python wheels Setup installs
(toolchain.PACKAGES into Setup's Python, tools/engine/build.py's VENV_PACKAGES into the engine venv). Run it after
changing either list (needs the internet: PyPI), and commit both files.
For each list and each target Python (TARGETS: Setup's own Python 3.13, Windows x64 and Linux x64), pip resolves the
list and its dependencies to wheels; every package then gets ONE version and the sha256 of every wheel of that version
that the target can install (PyPI's JSON API, the files PyPI serves), so pip --require-hashes accepts the wheel it
picks on any such PC and refuses any other bytes. A package one target needs and the other does not gets its
sys_platform marker; a package that resolves to two versions stops this script (pin it in the list).
    py tools/builder/lock_wheels.py [--check]   (--check: exit 1 when the files are not what this run makes)"""
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import toolchain  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
PY = '3.13'
# target: (pip download --platform values, sys_platform, wheel platform tag test)
TARGETS = {
    'win_amd64': (['win_amd64'], 'win32', lambda t: t == 'win_amd64'),
    'linux_x86_64': ([f'manylinux_2_{n}_x86_64' for n in (17, 28, 34)] + ['manylinux2014_x86_64', 'linux_x86_64'], 'linux',
                     lambda t: t == 'linux_x86_64' or re.fullmatch(r'manylinux(1|2010|2014|_\d+_\d+)_x86_64', t) is not None),
}


def venv_packages():
    src = open(os.path.join(REPO, 'tools', 'engine', 'build.py'), encoding='utf-8').read()
    return eval(re.search(r'^VENV_PACKAGES = (\[.*?\])', src, re.M | re.S)[1])   # (a literal list; build.py imports too much)


def norm(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def python_ok(py_tags, abi_tags):
    """a wheel's python / abi tags for CPython 3.13"""
    ver = int(PY.split('.')[1])
    for p in py_tags:
        if p in ('py3', 'py2.py3') and 'none' in abi_tags:
            return True
        m = re.fullmatch(r'cp3(\d+)', p)
        if m and (int(m[1]) == ver and abi_tags & {f'cp3{ver}', 'none', 'abi3'} or int(m[1]) <= ver and 'abi3' in abi_tags):
            return True
    return False


def fits(filename, target):
    """a wheel file this target's Python can install"""
    parts = filename[:-4].split('-')
    py_tags, abi_tags, plat_tags = parts[-3].split('.'), set(parts[-2].split('.')), parts[-1].split('.')
    return python_ok(py_tags, abi_tags) and any(t == 'any' or TARGETS[target][2](t) for t in plat_tags)


def resolve(specs, target):
    """{normalized name: version} of specs and their dependencies, as pip resolves them for target"""
    with tempfile.TemporaryDirectory(prefix='lock_wheels_') as d:
        plats = [a for p in TARGETS[target][0] for a in ('--platform', p)]
        r = subprocess.run([sys.executable, '-m', 'pip', 'download', '--disable-pip-version-check', '--quiet',
                            '--only-binary', ':all:', '--python-version', PY, '--implementation', 'cp', *plats,
                            '--dest', d, *specs], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'pip download for {target} failed:\n{(r.stdout + r.stderr)[-1500:]}')
        return {norm(n.split('-')[0]): n.split('-')[1] for n in os.listdir(d) if n.endswith('.whl')}


def pypi_files(name, version):
    with urllib.request.urlopen(f'https://pypi.org/pypi/{name}/{version}/json', timeout=60) as f:
        return [(u['filename'], u['digests']['sha256']) for u in json.load(f)['urls'] if u['filename'].endswith('.whl')]


def lock(specs):
    per = {t: resolve(specs, t) for t in TARGETS}
    lines = []
    for name in sorted(set().union(*per.values())):
        vers = {per[t][name] for t in TARGETS if name in per[t]}
        if len(vers) > 1:
            sys.exit(f'{name} resolves to {sorted(vers)} on the targets: pin one version in the list')
        ver = vers.pop()
        on = [t for t in TARGETS if name in per[t]]
        hashes = sorted({h for fn, h in pypi_files(name, ver) if any(fits(fn, t) for t in on)})
        if not hashes:
            sys.exit(f'{name}=={ver}: no wheel on PyPI for {on}')
        marker = '' if len(on) == len(TARGETS) else f' ; sys_platform == "{TARGETS[on[0]][1]}"'
        lines.append(f'{name}=={ver}{marker} \\\n' + ' \\\n'.join(f'    --hash=sha256:{h}' for h in hashes))
    return lines


def text(which, specs):
    targets = ' '.join(f'cp{PY.replace(".", "")}-{t}' for t in TARGETS)
    return (f'# Generated by tools/builder/lock_wheels.py (do not edit): {which} = {" ".join(specs)} and every\n'
            f'# dependency, one version each, with the sha256 of each wheel PyPI serves for it (pip --require-hashes)\n'
            f'# targets: {targets}\n' + '\n'.join(lock(specs)) + '\n')


def main():
    out = {'setup': toolchain.PACKAGES, 'venv': venv_packages()}
    bad = []
    for which, specs in out.items():
        if any('==' not in s for s in specs):
            sys.exit(f'{which}: every package needs a version (==): {[s for s in specs if "==" not in s]}')
        p = os.path.join(HERE, toolchain.WHEEL_LOCKS[which])
        t = text(which, specs)
        if '--check' in sys.argv:
            if not os.path.isfile(p) or open(p, encoding='utf-8').read() != t:
                bad.append(p)
            continue
        open(p, 'w', encoding='utf-8', newline='\n').write(t)
        print(p, t.count('--hash='), 'hashes')
    if bad:
        print('not current (run tools/builder/lock_wheels.py):', *bad)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())

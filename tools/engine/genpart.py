"""A key's generated main from a near key's (G16: a code mod rebuilt over the player's own build regenerated all 243k
functions, 126 s of a 7 min rebuild, to change a handful).

gen.py's text for a function depends on its own bytes and FDE size, on the bytes its jump tables read, and on four
module-wide inputs: which addresses are function starts (a direct call or musttail, else call_ind), the PLT, the
--lso-abi keep sets (its own call sites and start, and whether each direct callee is an `entry` reader) and gen_ext.py's
extension ranges / switch sites keyed by its start (genshard.py: nothing else carries between functions). So against a
base key generated by the same tools with the same arguments and split, when every byte that differs is inside a
function or an extension range, the functions whose text may differ are

  - those whose bytes, FDE size, extension ranges or switch sites differ, and new ones;
  - the function before a changed extension range outside every FDE (one in the padding after a function: that
    function's jump tables may read the words past its end, gen.py udf_at);
  - those whose call sites or start differ in the keep file, and the direct callers of an address that became or
    stopped being a function start or an `entry` reader (a scan of the image's branch words);

and every other function's text is the base's, byte for byte. affected() finds them, or says why it cannot (bytes
changed outside the code: the PLT or a jump table may read them; other funcs.json fields), regenerate() runs gen over
them only, and graft() lays the base key's TUs around them with tusplit.py's own cut: the tree a full gen + split
writes (a TU none of whose functions changed is the base's file, hard-linked). The base TUs' functions, weights and
declarations come from tusplit.INDEX, written beside the TUs by tusplit.split (made here once for an older base).
"""
import bisect, json, os, re, shutil, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # (python -I: --gen runs as a script, no script dir)
import tusplit  # noqa: E402

MAX_FUNCS = 4000     # more functions to regenerate than this: a full gen's shares are about as fast
TU = re.compile(r'[thc]_[0-9a-f]+\.cpp')


def load_funcs(fj):
    f = json.load(open(fj))
    fde = {int(k, 16): v for k, v in f['fde'].items()}
    ext = {int(k, 16): [(int(a, 16), int(b, 16)) for a, b in v] for k, v in f.get('ext', {}).items()}
    sw = {int(k, 16): v for k, v in f.get('switch', {}).items()}
    rest = {k: v for k, v in f.items() if k not in ('fde', 'ext', 'switch')}
    return fde, ext, sw, rest


def read_keep(path, mod):
    """{(kind, address): registers text} of a keep file's module section"""
    out, cur = {}, None
    for line in open(path):
        p = line.split()
        if not p or line.startswith('#'):
            continue
        if p[0] == 'module':
            cur = p[1]
        elif cur == mod:
            out[(p[0], int(p[1], 16))] = p[2] if len(p) > 2 else ''
    return out


def diff_runs(a, b, block=1 << 16):
    """[start, end) runs where two images differ (a longer one's tail is a difference)"""
    runs, n = [], max(len(a), len(b))
    same = lambda k: k < len(a) and k < len(b) and a[k] == b[k]   # noqa: E731
    for o in range(0, n, block):
        if a[o:o + block] == b[o:o + block]:
            continue
        k, end = o, min(n, o + block)
        while k < end:
            if same(k):
                k += 1
                continue
            j = k
            while j < end and not same(j):
                j += 1
            if runs and runs[-1][1] == k:
                runs[-1][1] = j
            else:
                runs.append([k, j])
            k = j
    return runs


class Code:
    """the module's functions and extension ranges by address"""

    def __init__(self, fde, ext):
        self.starts = sorted(fde)
        self.fde = fde
        self.ext = sorted((a, b, f) for f, rr in ext.items() for a, b in rr)
        self.ext_lo = [x[0] for x in self.ext]

    def in_fde(self, a):
        j = bisect.bisect_right(self.starts, a) - 1
        return self.starts[j] if j >= 0 and a < self.starts[j] + self.fde[self.starts[j]] else None

    def owner(self, a):
        """the function whose code holds a: its FDE range or one of its extension ranges"""
        f = self.in_fde(a)
        if f is not None:
            return f
        k = bisect.bisect_right(self.ext_lo, a) - 1
        return self.ext[k][2] if k >= 0 and a < self.ext[k][1] else None

    def before(self, a):
        j = bisect.bisect_right(self.starts, a) - 1
        return self.starts[j] if j >= 0 else None


# direct branches by the top byte of their word (little-endian: byte 3): b / bl, b.cond, cbz / cbnz, tbz / tbnz, adr
_TOP = re.compile(rb'(?s)...[\x14-\x17\x94-\x97\x54\x34\x35\xb4\xb5\x36\x37\xb6\xb7\x10\x30\x50\x70\x90\xb0\xd0\xf0]')


def branch_target(w, p):
    top = w >> 24
    if top & 0x7c == 0x14:                                    # b, bl: imm26
        return p + (((w & 0x3ffffff) ^ 0x2000000) - 0x2000000) * 4
    if (top == 0x54 and not w & 0x10) or top & 0x7e == 0x34:   # b.cond, cbz / cbnz: imm19
        return p + ((((w >> 5) & 0x7ffff) ^ 0x40000) - 0x40000) * 4
    if top & 0x7e == 0x36:                                    # tbz / tbnz: imm14
        return p + ((((w >> 5) & 0x3fff) ^ 0x2000) - 0x2000) * 4
    if top & 0x9f == 0x10:                                    # adr: immhi:immlo
        imm = ((w >> 3) & 0x1ffffc) | ((w >> 29) & 3)
        return p + ((imm ^ 0x100000) - 0x100000)
    return None


def branches_to(img, targets, code):
    """the functions with a direct branch (or an adr) to one of targets, in their FDE or extension code"""
    out = set()
    for m in _TOP.finditer(img):
        p = m.start()
        if p & 3:
            continue
        if branch_target(int.from_bytes(img[p:p + 4], 'little'), p) in targets:
            f = code.owner(p)
            if f is not None:
                out.add(f)
    return out


def affected(img_n, img_b, fj_n, fj_b, keep_n, keep_b, mod):
    """(functions to regenerate, base functions gone, None), or (None, None, why a full gen)"""
    fde_n, ext_n, sw_n, rest_n = load_funcs(fj_n)
    fde_b, ext_b, sw_b, rest_b = load_funcs(fj_b)
    if rest_n != rest_b:
        return None, None, 'funcs.json differs beyond fde / ext / switch'
    code, code_b = Code(fde_n, ext_n), Code(fde_b, ext_b)
    redo = {s for s in fde_n if fde_b.get(s) != fde_n[s]}
    redo |= {s for s in set(ext_n) | set(ext_b) if ext_n.get(s) != ext_b.get(s)}
    for a in set(sw_n) | set(sw_b):
        if sw_n.get(a) != sw_b.get(a):
            f = code.owner(a)
            if f is None:
                return None, None, f'a switch site outside the code at {a:#x}'
            redo.add(f)
    a_img, b_img = open(img_n, 'rb').read(), open(img_b, 'rb').read()
    for a, b in diff_runs(a_img, b_img):
        for p in range(a, b):
            # (code in either image: a base key's own extension can sit where this image has padding again)
            f = code.owner(p) if code.owner(p) is not None else code_b.owner(p)
            if f is None:
                return None, None, f'bytes changed outside the code at {p:#x} (the PLT or a jump table may read them)'
            redo.add(f)
            if code.in_fde(p) is None:   # (an extension range: the function before it may read past its own end)
                g = code.before(p)
                if g is not None:
                    redo.add(g)
    kn, kb = (read_keep(keep_n, mod), read_keep(keep_b, mod)) if keep_n else ({}, {})   # (None: no --lso-abi)
    targets = set(fde_n) ^ set(fde_b)
    for kind, a in {k for k in set(kn) | set(kb) if kn.get(k) != kb.get(k)}:
        if kind == 'entry':
            targets.add(a)
        elif kind == 'callee':
            redo.add(a)
        else:
            f = code.owner(a)
            if f is not None:
                redo.add(f)
    if targets:
        redo |= branches_to(a_img, targets, code)
    return {f for f in redo if f in fde_n}, set(fde_b) - set(fde_n), None


def regenerate(py, tool, img_prefix, fj, part, args, funcs, log_file):
    """gen.py / gen_ext.py over `funcs` only (its --only, the list in a file: too long for a command line), into part"""
    shutil.rmtree(part, ignore_errors=True)
    os.makedirs(part)
    lst = part + '.only.txt'
    with open(lst, 'w') as f:
        f.write(','.join(f'{s:x}' for s in sorted(funcs)))
    try:
        cmd = [py, '-I', os.path.abspath(__file__), '--gen', tool, img_prefix, fj, part, lst] + list(args)
        with open(log_file, 'w') as lf:
            lf.write('$ ' + ' '.join(cmd) + '\n')  # (what ran, for a check against a full gen)
            lf.flush()
            subprocess.check_call(cmd, stdout=lf, stderr=subprocess.STDOUT)
    finally:
        os.remove(lst)


def _blank_module():
    m = tusplit.Module.__new__(tusplit.Module)
    m.pre, m.decl, m.funcs, m.defs, m.other, m.eol = None, {}, {}, {}, [], None
    return m


def with_definitions(decl, m):
    """tusplit.split's declarations: gen.py's, and one made from the definition of a function gen.py never declared"""
    for b in m.funcs.values():
        for line in b.split(m.eol):
            d = tusplit.DEF.match(line)
            if d and d.group(1) not in decl:
                decl[d.group(1)] = line[:line.index(') {') + 1] + ';'
    return decl


def make_index(d):
    """tusplit.INDEX of a split gen dir made before tusplit wrote one: every TU parsed once"""
    m = _blank_module()
    files = {}
    for fn in sorted(f for f in os.listdir(d) if TU.fullmatch(f)):
        before = set(m.funcs)
        m.parse(os.path.join(d, fn))
        files.update((n, fn) for n in m.funcs.keys() - before)
    tusplit.write_index(d, m, with_definitions(dict(m.decl), m),
                        {n: tusplit.weight(b) for n, b in m.funcs.items()}, files)


def load_index(d):
    for attempt in (0, 1):
        try:
            idx = json.load(open(os.path.join(d, tusplit.INDEX)))
            if idx.get('version') == tusplit.INDEX_VERSION:
                return idx
        except (OSError, ValueError):
            pass
        if not attempt:
            make_index(d)
    raise ValueError(f'{d}: no {tusplit.INDEX}')


def graft(base_gen, part, gone, out, target, hot, link, note):
    """out = base_gen's split tree with part's functions (gen.py --only output, unsplit; None: none) in place of theirs
    and the `gone` ones out. Returns a summary like tusplit.split's."""
    idx = load_index(base_gen)
    new = tusplit.Module(part) if part else _blank_module()
    if new.funcs and (new.pre != idx['pre'] or new.eol != idx['eol']):
        raise ValueError("the regenerated TUs have another header than the base key's")
    if part and open(os.path.join(part, 'imports.cpp')).read() != open(os.path.join(base_gen, 'imports.cpp')).read():
        raise ValueError("imports.cpp differs from the base key's")
    redo = {tusplit.addr(n) for n in new.funcs} | set(gone)
    w = {n: wt for n, wt, _ in idx['funcs']}
    w.update({n: tusplit.weight(b) for n, b in new.funcs.items()})
    where = {n: fn for n, _, fn in idx['funcs']}
    base_tus = {}
    for n, _, fn in idx['funcs']:
        base_tus.setdefault(fn, []).append(n)
    # (stable: a base function keeps its place among those of its address, a regenerated one gen.py's, as in a split)
    order = sorted([n for n, _, _ in idx['funcs'] if tusplit.addr(n) not in redo] + list(new.funcs), key=tusplit.addr)
    decl = with_definitions({**idx['decl'], **new.decl}, new)
    for n in [n for n in decl if n not in new.funcs and tusplit.DECL.match(decl[n]) and re.fullmatch(r'[a-z]+_[0-9a-f]+', n)
              and int(n.split('_')[1], 16) in gone]:
        del decl[n]   # (a function gone: nothing declares it any more; only the index would still list it)
    classes = {'t': order} if hot is None else {'h': [n for n in order if n in hot],
                                                 'c': [n for n in order if n not in hot]}
    os.makedirs(out, exist_ok=True)
    parsed, pattern, files = _blank_module(), None, {}
    summary = {'functions': len(order), 'tus': {}, 'regenerated': len(new.funcs), 'tus_written': 0}
    for cls, names in classes.items():
        count = 0
        for group in tusplit.chunks(names, w, target):
            fn = f'{cls}_{tusplit.addr(group[0]):010x}.cpp'
            files.update((n, fn) for n in group)
            count += 1
            if base_tus.get(fn) == group and not any(n in new.funcs for n in group):
                link(os.path.join(base_gen, fn), os.path.join(out, fn))
                continue
            for n in group:
                if n not in new.funcs and n not in parsed.funcs:
                    parsed.parse(os.path.join(base_gen, where[n]))
            bodies = [new.funcs[n] if n in new.funcs else parsed.funcs[n] for n in group]
            pattern = pattern or tusplit.ref_pattern(decl)
            refs = {t for b in bodies for t in pattern.findall(b) if t in decl}
            with open(os.path.join(out, fn), 'w', newline='') as f:
                f.write(tusplit.render(idx['pre'], sorted(decl[r] for r in refs), bodies, idx['eol']))
            summary['tus_written'] += 1
        summary['tus'][cls] = count
    # ftab.cpp: the base's lines but the redone and gone functions', the regenerated ones' in, in address order
    from genshard import ftab_parts
    b0 = ftab_parts(open(os.path.join(base_gen, 'ftab.cpp')).read())
    p0 = ftab_parts(open(os.path.join(part, 'ftab.cpp')).read()) if part else (b0[0], '', b0[2], '', b0[4])
    if (b0[0], b0[2], b0[4]) != (p0[0], p0[2], p0[4]):
        raise ValueError("ftab.cpp head or tail differs from the base key's")
    at = re.compile(r'(?:void \w+?_|\{0x)([0-9a-f]+)')

    def merged(base, mine):
        lines = [ln for ln in base.splitlines(True) if int(at.search(ln).group(1), 16) not in redo]
        return ''.join(sorted(lines + mine.splitlines(True), key=lambda ln: int(at.search(ln).group(1), 16)))
    with open(os.path.join(out, 'ftab.cpp'), 'w') as f:
        f.write(b0[0] + merged(b0[1], p0[1]) + b0[2] + merged(b0[3], p0[3]) + b0[4])
    rep = json.load(open(os.path.join(base_gen, 'report.json')))
    rep['partial'] = dict(note, regenerated=len(new.funcs), gone=len(gone), tus_written=summary['tus_written'])
    json.dump(rep, open(os.path.join(out, 'report.json'), 'w'), indent=1)
    for fn in os.listdir(base_gen):   # (imports.cpp and anything else the split passed through)
        if fn not in ('ftab.cpp', 'report.json', tusplit.INDEX) and not TU.fullmatch(fn):
            link(os.path.join(base_gen, fn), os.path.join(out, fn))
    m = _blank_module()
    m.pre, m.eol = idx['pre'], idx['eol']
    tusplit.write_index(out, m, decl, w, files)
    return summary



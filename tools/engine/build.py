def stale_features(pset: dict) -> list:
    """Each feature whose words in an exported patch set differ from games/totk/patches/v100.toml now (what an export
    today would write: the rows whose new word differs from the original).
    from older exports under the same feature name; a stale export is a build error, not a fight crash."""
    import tomllib
    with open(PATCH_TABLE, 'rb') as f:
        table = tomllib.load(f)
    # The table holds no word of the game: a row is our new word, or copy_of (the image's own word moved into a veneer,
    # compared by offset alone); a copy of a word onto itself is a checked guard, not a change (not in the export).
    feats = set(pset.get('features', []))
    want, have = {}, {}
    for r in table['patch']:
        if r['feature'] in feats and r.get('copy_of', -1) != r['offset']:
            want.setdefault(r['feature'], set()).add((r['offset'], r['new'].lower() if 'new' in r else 'copy'))
    copies = {(r['feature'], r['offset']) for r in table['patch'] if 'copy_of' in r}
    for p in pset['patches']:
        name, off = p.get('name', '?'), int(str(p['offset']), 0)
        have.setdefault(name, set()).add((off, 'copy' if (name, off) in copies else p['bytes'].lower()))
    out = []
    for name in sorted(set(want) | set(have)):
        w, h = want.get(name, set()), have.get(name, set())
        if w != h:
            out.append(f'{name} has {len(h)} words, the table {len(w)} ({len(w - h)} missing, {len(h - w)} not in it)')
    return out


def key_patches_stale(man: dict):
    """A built key's own patch set (<img>/patches.json, the manifest's img) checked against v100.toml now: None when
    current (or unpatched), else the message. A key built from an older export keeps its old words under the same
    feature names, and a runtime relinked on it later would ship them: the key build's check (images) has long
    passed by then."""
    p = os.path.join(man.get('img') or '', 'patches.json')
    try:
        with open(p) as f:
            pset = json.load(f)
    except (OSError, ValueError):
        return None
    if not pset.get('patches'):
        return None
    stale = stale_features(pset)
    if not stale:
        return None
    return (f"key {man.get('key')} was built from a stale patch set ({man.get('patches')}): " + '; '.join(stale)
            + '. A runtime linked on it carries the old words under the same feature names (E14): build the key again '
              'from a fresh export (python -m games.totk.patches engine ...)')



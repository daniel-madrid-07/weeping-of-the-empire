LINUX = sys.platform.startswith('linux')   # (v0.1.8.x has no Linux build; main defines it near the imports)


def builder_alive(pid):
    """the lock's holder still runs as a Python (a build.py): tasklist's output read as bytes, because the console code
    page varies (on a Spanish Windows text=True raised UnicodeDecodeError in the reader thread, stdout came back None
    and a Setup resumed after a stop failed at step 5 on the stale.lock); a pid reused by another program counts as
    gone, else the build would wait on it forever"""
    if not pid:
        return False
    if LINUX:
        try:
            os.kill(pid, 0)
        except OSError:
            return False
        try:
            return 'python' in open(f'/proc/{pid}/comm').read().lower()
        except OSError:
            return True
    out = subprocess.run(['tasklist', '/FI', f'PID eq {pid}', '/FO', 'CSV', '/NH'], capture_output=True).stdout or b''
    for line in out.splitlines():
        f = [x.strip(b'"') for x in line.split(b'","')]
        if len(f) > 1 and f[1] == str(pid).encode():
            return f[0].lower().startswith(b'python')
    return False


class Lock:
    """one builder per key directory (a second one waits)"""
    def __init__(self, d):
        self.p = os.path.join(d, '.lock')

    def __enter__(self):
        while True:
            try:
                fd = os.open(self.p, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(fd, str(os.getpid()).encode()); os.close(fd)
                return self
            except FileExistsError:
                try:
                    pid = int(open(self.p).read() or 0)
                except (OSError, ValueError):
                    pid = 0
                if not builder_alive(pid):
                    os.remove(self.p); continue
                log(f'waiting: another build (pid {pid}) holds {self.p}')
                time.sleep(30)

    def __exit__(self, *a):
        try:
            os.remove(self.p)
        except OSError:
            pass


def link_or_copy(src, dst):
    """a hard link, else a copy: exFAT / FAT32 drives (USB drives, SD cards) make none (public #31: os.link raised
    WinError 1 'Incorrect function' at step 5 on an install folder on D:)"""
    try:
        os.link(src, dst)
    except FileExistsError:
        raise
    except OSError:
        if os.path.lexists(dst):   # (as os.link: never over an existing file)
            raise FileExistsError(17, 'the target exists', dst)
        shutil.copy2(src, dst)


def clone_links(src, dst):
    """hard-link copy of a key directory (files written later are replaced by rename, so the base stays intact)"""
    for d, _, files in os.walk(src):
        rel = os.path.relpath(d, src)
        if rel.split(os.sep)[0] in ('exe', '.lock'):
            continue
        os.makedirs(os.path.join(dst, rel), exist_ok=True)
        for fn in files:
            if fn in ('manifest.json', '.lock'):
                continue
            if fn in ('build.ninja', '.ninja_log', '.ninja_deps'):  # ninja writes these in place
                shutil.copy2(os.path.join(d, fn), os.path.join(dst, rel, fn))
                continue
            link_or_copy(os.path.join(d, fn), os.path.join(dst, rel, fn))


CLONE_SLACK = 8 << 30   # free space a copied base key leaves for the patched key's own compiles and link


def hard_links_ok(d):
    """whether d's drive makes hard links (exFAT / FAT32 do not)"""
    p = os.path.join(d, f'.linkprobe-{os.getpid()}')
    try:
        open(p, 'wb').close()
        os.link(p, p + '2')
        os.remove(p + '2')
        return True
    except OSError:
        return False
    finally:
        try:
            os.remove(p)
        except OSError:
            pass


def clone_base(bdir, kdir):
    """a patched key starts from the base key's files (only changed TUs recompile): hard links, or on a drive without them a
    copy (~12 GB) when it fits with CLONE_SLACK to spare, else nothing. Returns 'linked', 'copied' or 'skipped'."""
    bkey = os.path.basename(bdir)
    if hard_links_ok(kdir):
        log(f'patched key: hard-linking the base key {bkey} (only changed TUs recompile)')
        clone_links(bdir, kdir)
        return 'linked'
    size = sum(os.path.getsize(os.path.join(d, fn)) for d, _, files in os.walk(bdir)
               if os.path.relpath(d, bdir).split(os.sep)[0] not in ('exe', '.lock') for fn in files)
    free = shutil.disk_usage(kdir).free
    if free < size + CLONE_SLACK:
        log(f'patched key: this drive makes no hard links and a copy of the base key {bkey} ({size / 2**30:.1f} GB) '
            f'does not fit in {free / 2**30:.1f} GB free with {CLONE_SLACK >> 30} GB to spare: every TU compiles')
        return 'skipped'
    log(f'patched key: this drive makes no hard links: copying the base key {bkey} ({size / 2**30:.1f} GB; only '
        'changed TUs recompile)')
    clone_links(bdir, kdir)
    return 'copied'


GEN_FREE_PARTS = ('variant', 'objs', 'clang', 'giants')   # key parts that change objects, never generated sources


def gen_id(parts):
    """what a key's generated sources (gen\\, funcs_*.json) follow from: its parts but the compile-only ones"""
    return sha(json.dumps({k: v for k, v in parts.items() if k not in GEN_FREE_PARTS}, sort_keys=True).encode())[:16]


def gen_twin(parts, kdir):
    """another key dir whose gen is done from the same inputs (the -O2 key of a --package / --pgo / --opt one, or the
    reverse): its gen\\ is hard-linked instead of a 1.5-2 min _gen (2026-10-30: 18 keys in 4 days, gen 58% of a warm
    key). sync_tree unlinks before it writes, so neither key ever writes through the other's files."""
    want = gen_id(parts)
    for s in ('game', 'game-var'):
        try:
            dirs = [e.path for e in os.scandir(os.path.join(SIG, s)) if e.is_dir()]
        except OSError:
            continue
        for d in dirs:
            if os.path.normcase(d) == os.path.normcase(kdir):
                continue
            try:
                man = json.load(open(os.path.join(d, 'manifest.json')))
            except (OSError, ValueError):
                continue
            if (man.get('gen_done') and isinstance(man.get('parts'), dict) and gen_id(man['parts']) == want
                    and not key_files_gone(d, man) and os.path.isdir(os.path.join(d, 'gen', 'sdk'))):
                return d
    return None


def link_gen(src, dst):
    """src's gen\\ and funcs_*.json into dst by hard links (dst's own gen\\ goes first: a base key's clone may hold TUs
    the twin does not; removing a link leaves the other key's file)"""
    shutil.rmtree(os.path.join(dst, 'gen'), ignore_errors=True)
    for d, _, files in os.walk(os.path.join(src, 'gen')):
        rel = os.path.relpath(d, src)
        os.makedirs(os.path.join(dst, rel), exist_ok=True)
        for fn in files:
            t = os.path.join(dst, rel, fn)
            if os.path.exists(t):
                os.remove(t)
            link_or_copy(os.path.join(d, fn), t)
    for fn in os.listdir(src):
        if fn.startswith('funcs_') and fn.endswith('.json'):
            shutil.copy2(os.path.join(src, fn), os.path.join(dst, fn))


def sync_tree(new, cur):
    """write-if-changed: cur gets new's files; unchanged files keep their mtime. Returns (changed, removed)."""
    os.makedirs(cur, exist_ok=True)
    changed = 0
    names = set(os.listdir(new))
    for fn in names:
        a, b = os.path.join(new, fn), os.path.join(cur, fn)
        if os.path.exists(b) and os.path.getsize(a) == os.path.getsize(b) and fsha(a) == fsha(b):
            continue
        if os.path.exists(b):
            os.remove(b)          # (a hard link to the base: unlink, never write through it)
        os.replace(a, b)
        changed += 1
    removed = 0
    for fn in set(os.listdir(cur)) - names:
        os.remove(os.path.join(cur, fn)); removed += 1
    return changed, removed


def with_veneers(fj, pset):
    """Game patches' veneers (the doc): `fde_add` = functions to add, `ext` = code outside a function's FDE that
    belongs to it (gen_ext.py decodes it as part of the function)."""
    funcs = json.load(open(fj))
    for s, n in pset.get('fde_add', {}).items():
        funcs['fde'][hex(int(s, 16))] = n
    for f in pset.get('ext', {}):
        if hex(int(f, 16)) not in funcs['fde']:
            sys.exit(f'patch set ext: {f} is not a function start in {fj}')
    funcs['ext'] = pset.get('ext', {})
    if pset.get('switch'):   # (switch sites: words chosen at run time, the mods' code cheats; gen_ext.py ExtEmitter)
        funcs['switch'] = pset['switch']
    json.dump(funcs, open(fj, 'w', newline='\n'), indent=1)


def uses_gen_ext(pset):
    """main is generated by gen_ext.py: the patch set has veneers or switch sites"""
    return bool(pset.get('ext') or pset.get('fde_add') or pset.get('switch'))


def gen(img, kdir):
    pset = patch_set(img)
    hot = set(open(HOT).read().split()) if HOT else None

    def one(mod, args):
        t0 = time.time()
        fj = os.path.join(kdir, f'funcs_{mod}.json')
        run([PY, '-I', os.path.join(TOOLS, 'tools', 'funcs.py'), os.path.join(img, mod), fj + '.tmp'], stdout=subprocess.DEVNULL)
        veneers = mod == 'main' and uses_gen_ext(pset)
        if veneers:
            with_veneers(fj + '.tmp', pset)
        os.replace(fj + '.tmp', fj)
        args = lso_abi_auto(args, mod, fj, img)
        tmp = os.path.join(kdir, 'gen.tmp', mod)
        shutil.rmtree(tmp, ignore_errors=True)
        tool = os.path.join(TOOLS, 'tools', 'recomp', 'gen_ext.py' if veneers else 'gen.py')
        if not SPLIT:
            with open(os.path.join(kdir, f'gen_{mod}.log'), 'w') as lf:
                run([PY, '-I', tool, os.path.join(img, mod), fj, tmp] + args, stdout=lf)
        else:
            # shares of the functions at once (genshard.py; the split output does not depend on the shares)
            n = gen_shares(mod)
            shares = [f'{tmp}.{i}' for i in range(n)]

            def share(i):
                with open(os.path.join(kdir, f'gen_{mod}.{i}.log'), 'w') as lf:
                    run([PY, '-I', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'genshard.py'), tool, i, n,
                         os.path.join(img, mod), fj, shares[i]] + args, stdout=lf)
            with ThreadPoolExecutor(n) as ex:
                for f in [ex.submit(share, i) for i in range(n)]:
                    f.result()
            genshard.merge(tmp, shares)
            for d in shares:
                shutil.rmtree(d)
        t1 = time.time()
        if SPLIT:
            s = tusplit.split(tmp, tmp + '.split', SPLIT, hot)
            log(f'split {mod}: {s["functions"]} functions -> {s["tus"]} TUs ({time.time() - t1:.0f} s)')
            shutil.rmtree(tmp); tmp += '.split'
        c, r = sync_tree(tmp, os.path.join(kdir, 'gen', mod))
        log(f'gen {mod}: {c} files changed, {r} removed ({t1 - t0:.0f} s gen)')
    # main and sdk at once (two single-threaded gen.py runs)
    with ThreadPoolExecutor(2) as ex:
        for f in [ex.submit(one, 'main', gen_args(GEN_MAIN)), ex.submit(one, 'sdk', gen_args(GEN_SDK))]:
            f.result()
    shutil.rmtree(os.path.join(kdir, 'gen.tmp'), ignore_errors=True)



def game_jobs(cap):
    """game-object compiles at once: what the free commit carries above heavy.py's build floor once GIANT_POOL giants
    peak (TU_COMMIT_GB a compile), between GAME_JOBS_MIN and cap"""
    heavy = heavy_mod()
    free = heavy.free_commit_gb()
    fit = int((free - heavy.COMMIT_FLOOR_GB['heavy'] - GIANT_POOL * GIANT_PEAK_GB) / TU_COMMIT_GB)
    jobs = max(min(GAME_JOBS_MIN, cap), min(cap, fit))
    log(f'game objects: {jobs} compiles at once (free commit {free:.1f} GB, cap {cap})')
    return jobs


def cmd_ninja(kdir, jobs, file='build.ninja', stop=None):
    """(internal, run by heavy.py) ninja on the game objects (all it can: -k 0), or a runtime dir (`stop`: at the
    first error). jobs `autoN`: game_jobs(N), from the free commit now"""
    ensure_venv()
    if jobs.startswith('auto'):
        jobs = game_jobs(int(jobs[4:]))
    # the game objects' measured-boot limit (commitgate.py --excl) loosens EXCL_BOUND_MIN after ninja starts, for the
    # whole build (per compile, boots back to back would hold each new compile its own bound)
    env = dict(build_env(), NXR_COMMITGATE_EXCL_UNTIL=str(time.time() + 60 * EXCL_BOUND_MIN))
    if SOLO:   # one person's PC: a compile short of commit waits SOLO_GATE_MIN, then runs (objects() retries failures)
        env.update(NXR_COMMITGATE_GO_ON='1', NXR_COMMITGATE_MAX_MIN=str(SOLO_GATE_MIN))
    rc = subprocess.call([NINJA, '-C', kdir, '-f', file, f'-j{jobs}'] + ([] if stop else ['-k', '0']), env=env)
    sys.exit(rc)



class Lock:
    """one builder per key directory (a second one waits)"""
    def __init__(self, d):
        self.p = os.path.join(d, '.lock')

    def __enter__(self):
        while True:
            try:
                fd = os.open(self.p, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(fd, str(os.getpid()).encode()); os.close(fd)
                return self
            except FileExistsError:
                try:
                    pid = int(open(self.p).read() or 0)
                except (OSError, ValueError):
                    pid = 0
                alive = pid and subprocess.run(['tasklist', '/FI', f'PID eq {pid}', '/NH'], capture_output=True,
                                               text=True).stdout.find(str(pid)) >= 0
                if not alive:
                    os.remove(self.p); continue
                log(f'waiting: another build (pid {pid}) holds {self.p}')
                time.sleep(30)

    def __exit__(self, *a):
        try:
            os.remove(self.p)
        except OSError:
            pass


def clone_links(src, dst):
    """hard-link copy of a key directory (files written later are replaced by rename, so the base stays intact)"""
    for d, _, files in os.walk(src):
        rel = os.path.relpath(d, src)
        if rel.split(os.sep)[0] in ('exe', '.lock'):
            continue
        os.makedirs(os.path.join(dst, rel), exist_ok=True)
        for fn in files:
            if fn in ('manifest.json', '.lock'):
                continue
            if fn in ('build.ninja', '.ninja_log', '.ninja_deps'):  # ninja writes these in place
                shutil.copy2(os.path.join(d, fn), os.path.join(dst, rel, fn))
                continue
            os.link(os.path.join(d, fn), os.path.join(dst, rel, fn))


GEN_FREE_PARTS = ('variant', 'objs', 'clang', 'giants')   # key parts that change objects, never generated sources


def gen_id(parts):
    """what a key's generated sources (gen\\, funcs_*.json) follow from: its parts but the compile-only ones"""
    return sha(json.dumps({k: v for k, v in parts.items() if k not in GEN_FREE_PARTS}, sort_keys=True).encode())[:16]


def gen_twin(parts, kdir):
    """another key dir whose gen is done from the same inputs (the -O2 key of a --package / --pgo / --opt one, or the
    reverse): its gen\\ is hard-linked instead of a 1.5-2 min _gen (2026-10-30: 18 keys in 4 days, gen 58% of a warm
    key). sync_tree unlinks before it writes, so neither key ever writes through the other's files."""
    want = gen_id(parts)
    for s in ('game', 'game-var'):
        try:
            dirs = [e.path for e in os.scandir(os.path.join(SIG, s)) if e.is_dir()]
        except OSError:
            continue
        for d in dirs:
            if os.path.normcase(d) == os.path.normcase(kdir):
                continue
            try:
                man = json.load(open(os.path.join(d, 'manifest.json')))
            except (OSError, ValueError):
                continue
            if (man.get('gen_done') and isinstance(man.get('parts'), dict) and gen_id(man['parts']) == want
                    and not key_files_gone(d, man) and os.path.isdir(os.path.join(d, 'gen', 'sdk'))):
                return d
    return None


def link_gen(src, dst):
    """src's gen\\ and funcs_*.json into dst by hard links (dst's own gen\\ goes first: a base key's clone may hold TUs
    the twin does not; removing a link leaves the other key's file)"""
    shutil.rmtree(os.path.join(dst, 'gen'), ignore_errors=True)
    for d, _, files in os.walk(os.path.join(src, 'gen')):
        rel = os.path.relpath(d, src)
        os.makedirs(os.path.join(dst, rel), exist_ok=True)
        for fn in files:
            t = os.path.join(dst, rel, fn)
            if os.path.exists(t):
                os.remove(t)
            os.link(os.path.join(d, fn), t)
    for fn in os.listdir(src):
        if fn.startswith('funcs_') and fn.endswith('.json'):
            shutil.copy2(os.path.join(src, fn), os.path.join(dst, fn))


def sync_tree(new, cur):
    """write-if-changed: cur gets new's files; unchanged files keep their mtime. Returns (changed, removed)."""
    os.makedirs(cur, exist_ok=True)
    changed = 0
    names = set(os.listdir(new))
    for fn in names:
        a, b = os.path.join(new, fn), os.path.join(cur, fn)
        if os.path.exists(b) and os.path.getsize(a) == os.path.getsize(b) and fsha(a) == fsha(b):
            continue
        if os.path.exists(b):
            os.remove(b)          # (a hard link to the base: unlink, never write through it)
        os.replace(a, b)
        changed += 1
    removed = 0
    for fn in set(os.listdir(cur)) - names:
        os.remove(os.path.join(cur, fn)); removed += 1
    return changed, removed


def with_veneers(fj, pset):
    """Game patches' veneers: `fde_add` = functions to add, `ext` = code outside a function's
    FDE that belongs to it (gen_ext.py decodes it as part of the function)."""
    funcs = json.load(open(fj))
    for s, n in pset.get('fde_add', {}).items():
        funcs['fde'][hex(int(s, 16))] = n
    for f in pset.get('ext', {}):
        if hex(int(f, 16)) not in funcs['fde']:
            sys.exit(f'patch set ext: {f} is not a function start in {fj}')
    funcs['ext'] = pset.get('ext', {})
    json.dump(funcs, open(fj, 'w', newline='\n'), indent=1)


def gen(img, kdir):
    pset = patch_set(img)
    hot = set(open(HOT).read().split()) if HOT else None

    def one(mod, args):
        t0 = time.time()
        fj = os.path.join(kdir, f'funcs_{mod}.json')
        run([PY, '-I', os.path.join(TOOLS, 'tools', 'funcs.py'), os.path.join(img, mod), fj + '.tmp'], stdout=subprocess.DEVNULL)
        veneers = mod == 'main' and (pset.get('ext') or pset.get('fde_add'))
        if veneers:
            with_veneers(fj + '.tmp', pset)
        os.replace(fj + '.tmp', fj)
        args = lso_abi_auto(args, mod, fj, img)
        tmp = os.path.join(kdir, 'gen.tmp', mod)
        shutil.rmtree(tmp, ignore_errors=True)
        tool = os.path.join(TOOLS, 'tools', 'recomp', 'gen_ext.py' if veneers else 'gen.py')
        if not SPLIT:
            with open(os.path.join(kdir, f'gen_{mod}.log'), 'w') as lf:
                run([PY, '-I', tool, os.path.join(img, mod), fj, tmp] + args, stdout=lf)
        else:
            # shares of the functions at once (genshard.py; the split output does not depend on the shares)
            n = GEN_SHARES[mod]
            shares = [f'{tmp}.{i}' for i in range(n)]

            def share(i):
                with open(os.path.join(kdir, f'gen_{mod}.{i}.log'), 'w') as lf:
                    run([PY, '-I', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'genshard.py'), tool, i, n,
                         os.path.join(img, mod), fj, shares[i]] + args, stdout=lf)
            with ThreadPoolExecutor(n) as ex:
                for f in [ex.submit(share, i) for i in range(n)]:
                    f.result()
            genshard.merge(tmp, shares)
            for d in shares:
                shutil.rmtree(d)
        t1 = time.time()
        if SPLIT:
            s = tusplit.split(tmp, tmp + '.split', SPLIT, hot)
            log(f'split {mod}: {s["functions"]} functions -> {s["tus"]} TUs ({time.time() - t1:.0f} s)')
            shutil.rmtree(tmp); tmp += '.split'
        c, r = sync_tree(tmp, os.path.join(kdir, 'gen', mod))
        log(f'gen {mod}: {c} files changed, {r} removed ({t1 - t0:.0f} s gen)')
    # main and sdk at once (two single-threaded gen.py runs)
    with ThreadPoolExecutor(2) as ex:
        for f in [ex.submit(one, 'main', gen_args(GEN_MAIN)), ex.submit(one, 'sdk', gen_args(GEN_SDK))]:
            f.result()
    shutil.rmtree(os.path.join(kdir, 'gen.tmp'), ignore_errors=True)


def rt_include(root):
    """rt.h at a path that depends only on its content: the game objects' command lines stay the same across HEADs"""
    h = fsha(os.path.join(root, 'runtime', 'rt.h'))[:12]
    d = os.path.join(SIG, 'rth', h)
    if not os.path.exists(os.path.join(d, 'rt.h')):
        os.makedirs(d, exist_ok=True)
        shutil.copy2(os.path.join(root, 'runtime', 'rt.h'), os.path.join(d, 'rt.h'))
    return d


def toolset() -> str:
    """the C/C++ headers rt.h pulls in come from the MSVC toolset and the Windows SDK, not from clang: their include
    paths name both versions (msvc_env exports no version variables)"""
    return build_env().get('INCLUDE', '')


def pgo_profile(path):
    """a .profdata in <work>/engine/pgo/ under its content's name: the compile rule (and so the object ids) name it"""
    h = fsha(path)[:16]
    d = os.path.join(SIG, 'pgo')
    p = os.path.join(d, f'{h}.profdata')
    if not os.path.exists(p):
        os.makedirs(d, exist_ok=True)
        shutil.copy2(path, p + '.tmp'); os.replace(p + '.tmp', p)
    return h, p


# the key parts that make the generated functions' bodies (or read the profile): clang drops the profile data of a
# function whose body changed since the training, so each one that differs means less of the gain
PGO_PARTS = ('main.bin', 'sdk.bin', 'gen.py', 'funcs.py', 'gen args', 'rt.h', 'gen_ext.py', 'veneers', 'clang')


def pgo_age(parts):
    """VARIANT's profile against its training record (<work>/engine/pgo/<sha>.json, tools/engine/pgo_train.py): the
    PGO_PARTS of `parts` that differ from the trained key's, [] when none, None without a profile in use"""
    if VARIANT.get('pgo') in (None, 'gen'):
        return None
    p = os.path.join(SIG, 'pgo', VARIANT['pgo'] + '.json')
    if not os.path.exists(p):
        return ['(no training record)']
    trained = json.load(open(p))['parts']
    return [k for k in PGO_PARTS if trained.get(k) != parts.get(k)]


# Runtime PGO (VARIANT 'pgo_rt'): the render thread, the HLE services and the rest of engine/runtime are not generated
# code, and with the game objects alone PGO bought the render thread -0.7 %. --pgo gen now instruments the runtime
# too; a profile whose training record says it holds the runtime's functions (pgo_train.py merge: 'runtime') compiles
# it with them, and older profiles keep their keys. A static function's profile name is "<source path>;<name>", and a
# package's runtime compiles from another tree than the training's, so the names use the file's base name only, in
# both compiles (game objects too: their static helpers).
PGO_NAMES = '-mllvm -static-func-full-module-prefix=false'


def pgo_record(sha):
    """the training record of profile `sha` (<work>/engine/pgo/<sha>.json), {} without one"""
    p = os.path.join(SIG, 'pgo', sha + '.json')
    return json.load(open(p)) if os.path.exists(p) else {}


def variant_rule(rule, hot):
    """the game rule with VARIANT's compile flags: --opt (hot TUs only; cold ones keep
    COLD_OPT), --march, --pgo gen (IR instrumentation) / --pgo <profdata> (use), --lto thin"""
    if not VARIANT:
        return rule
    if VARIANT.get('opt') and hot:
        rule = rule.replace(' -O2 ', f" {VARIANT['opt']} ")
    if VARIANT.get('march'):
        if '-march=x86-64-v3' not in rule:
            sys.exit('`rule gen` has no -march=x86-64-v3 to replace')
        rule = rule.replace('-march=x86-64-v3', f"-march={VARIANT['march']}")
    extra = []
    if VARIANT.get('pgo') == 'gen':
        extra.append('-fprofile-generate')
    elif VARIANT.get('pgo'):
        extra.append(f"-fprofile-use={os.path.join(SIG, 'pgo', VARIANT['pgo'] + '.profdata')}")
    if VARIANT.get('pgo_rt'):
        extra.append(PGO_NAMES)
    if VARIANT.get('lto'):
        extra.append(f"-flto={VARIANT['lto']}")
    if extra:
        if rule.count(' -c $in -o $out') != rule.count('$cxx '):
            sys.exit('`rule gen`: a compile without `-c $in -o $out`')
        rule = rule.replace(' -c $in -o $out', f" {' '.join(extra)} -c $in -o $out")
    return rule


FUNC_DEF = re.compile(rb'void ([fs]_[0-9a-f]+)\(Ctx\* __restrict cx\) \{')


def giant_of(src):
    """(lines, name) of the TU's largest function when it has GIANT_LINES lines or more, else (0, None); TUs under
    GIANT_LINES * 50 bytes are not read (generated code runs ~65 bytes a line)"""
    if not GIANT_LINES or os.path.getsize(src) < GIANT_LINES * 50:
        return 0, None
    data = open(src, 'rb').read()
    defs, i = [], data.find(b'\nvoid ')
    while i >= 0:     # (bytes.find, not a multiline regex over the whole TU: 1176 TUs in a few seconds)
        m = FUNC_DEF.match(data, i + 1)
        if m:
            defs.append((i + 1, m.group(1).decode()))
        i = data.find(b'\nvoid ', i + 1)
    best = (0, None)
    for (start, name), nxt in zip(defs, [d[0] for d in defs[1:]] + [len(data)]):
        n = data.count(b'\n', start, nxt)
        if n > best[0]:
            best = (n, name)
    return best if best[0] >= GIANT_LINES else (0, None)


def objects(kdir, jobs, prio, cache):
    """the game objects of build.ninja (mkninja_win.py --game-only). TUs named c_* (a split key's cold functions) use a
    copy of `rule gen` at COLD_OPT, and so do giant TUs (giant_of) unless their function is in GIANT_HOT; giants build
    in the ninja pool `giant`, first. With `cache`, an object whose id (TU bytes + its rule's text + clang + toolset) is
    in CACHE is hard-linked from there instead of compiled, and every object compiled here goes in. Returns stats."""
    text = open(os.path.join(kdir, 'build.ninja')).read()
    head = text[:text.index('\nbuild ') + 1]
    m = re.search(r'^rule gen\n(?:  .*\n)+', head, re.M)
    if not m or ' -O2 ' not in m.group(0):
        sys.exit(f'{kdir}/build.ninja: no `rule gen` with -O2 to derive the cold rule from')
    gen = m.group(0)
    if NOLINES:
        if ' -gline-tables-only' not in gen:
            sys.exit(f'{kdir}/build.ninja: `rule gen` has no -gline-tables-only to drop')
        gen = gen.replace('rule gen\n', 'rule gen_nolines\n', 1).replace(' -gline-tables-only', '')
    if VARIANT:
        gen = gen.replace(gen.split('\n')[0], 'rule gen_var', 1)
    hot = gen.split('\n')[0][len('rule '):]
    cold = gen.replace(f'rule {hot}\n', 'rule gen_cold\n', 1).replace(' -O2 ', f' {COLD_OPT} ')
    rules = {hot: variant_rule(gen, True), 'gen_cold': variant_rule(cold, False)}
    edges = re.findall(r'^build (\S+): gen (\S+)$', text, re.M)
    salt = '\0'.join([clang_version(), toolset(), ''])
    todo, hits, placed, giants = [], 0, set(), {}
    for obj, src in edges:
        rule = 'gen_cold' if os.path.basename(src).startswith('c_') else hot
        o, s = os.path.join(kdir, obj), os.path.join(kdir, src)
        lines, name = giant_of(s)
        if lines:
            giants[obj] = lines
            if rule == hot and name not in GIANT_HOT and not os.path.basename(src).startswith('h_'):
                rule = 'gen_cold'    # (an h_ TU: hot by --hot's profile, stays at -O2)
        placed.add(os.path.normcase(os.path.abspath(o)))
        oid = None
        if cache:
            h = hashlib.sha256((salt + rules[rule] + '\0').encode())
            with open(s, 'rb') as f:
                for b in iter(lambda: f.read(1 << 20), b''):
                    h.update(b)
            oid = h.hexdigest()
            c = os.path.join(CACHE, oid[:2], oid + '.o')
            if os.path.exists(c):
                if not (os.path.exists(o) and os.path.samefile(c, o)):
                    os.makedirs(os.path.dirname(o), exist_ok=True)
                    if os.path.exists(o):
                        os.remove(o)
                    os.link(c, o)
                hits += 1
                continue
            if os.path.exists(o) and os.stat(o).st_nlink > 1:
                os.remove(o)      # (a link into the cache or a base key: the compiler must never write through it)
        todo.append((obj, src, rule, oid))
    for sub in ('gen', 'sdk'):    # objects of TUs that are gone (a re-split key)
        d = os.path.join(kdir, 'obj', sub)
        for fn in os.listdir(d) if os.path.isdir(d) else []:
            p = os.path.join(d, fn)
            if fn.endswith('.o') and os.path.normcase(os.path.abspath(p)) not in placed:
                os.remove(p)
    ng = sum(1 for t in todo if t[0] in giants)
    log(f'game objects: {len(edges)} TUs, {hits} from the cache, {len(todo)} to compile '
        f'({sum(1 for t in todo if t[2] == "gen_cold")} at {COLD_OPT}; {ng} giants, {GIANT_POOL} at a time, each '
        f'with free commit >= {GIANT_COMMIT_GB:g} GB)')
    t0 = time.time()
    rc = 0
    if todo:
        cap = int(os.environ.get('NXR_GAME_JOBS_MAX') or GAME_JOBS_MAX)
        if int(jobs) > cap:
            log(f'game objects: --jobs {jobs} capped at {cap} (GAME_JOBS_MAX, E11 commit floor)')
            jobs = cap
        # every rule behind commitgate.py, a giant's with the commit floor too (the object id stays the ungated
        # rule's); at --prio high no wait for measured boots
        gate = f'"{sys.executable}" "{os.path.join(os.path.dirname(os.path.abspath(__file__)), "commitgate.py")}" '
        excl = '' if prio == 'high' else '--excl gpu '
        build_floor = heavy_mod().COMMIT_FLOOR_GB['heavy']
        grules = {}
        for r, giant in {(t[2], t[0] in giants) for t in todo}:
            if rules[r].count(f'rule {r}\n') != 1 or rules[r].count('\n  command = ') != 1:
                sys.exit(f'{kdir}: rule {r} has no single `rule {r}` / `  command = ` line to gate:\n{rules[r]}')
            name, floor = (f'{r}_giant', f'{GIANT_COMMIT_GB:g}') if giant else (f'{r}_gated', f'{build_floor:g}')
            grules[name] = rules[r].replace(f'rule {r}\n', f'rule {name}\n', 1).replace(
                '\n  command = ', f'\n  command = {gate}{floor} {excl}-- ', 1)
        # the compiles at once: `pool gen` (mkninja_win's --gen-pool, an older key's 3) up to the cap, ninja's -j
        # (game_jobs, when it starts) below it
        head = re.sub(r'^pool gen\n  depth = \d+$', f'pool gen\n  depth = {jobs}', head, count=1, flags=re.M)
        with open(os.path.join(kdir, 'objs.ninja'), 'w', newline='\n') as f:
            f.write(head + ''.join(t for r, t in rules.items() if r != 'gen'))   # (`rule gen` is in head)
            f.write(''.join(grules.values()) + f'pool giant\n  depth = {GIANT_POOL}\n')
            # the slowest first: ninja starts edges in file order, and the big TUs set the tail; giants (largest
            # function first) ahead of the rest, so they start early and never more than GIANT_POOL at once
            for obj, src, rule, _ in sorted(todo, key=lambda t: (-giants.get(t[0], 0),
                                                                 -os.path.getsize(os.path.join(kdir, t[1])))):
                f.write(f'build {obj}: {rule}_giant {src}\n  pool = giant\n' if obj in giants else
                        f'build {obj}: {rule}_gated {src}\n')
        cmd = [sys.executable, HEAVY, '--prio', prio, '--', sys.executable, os.path.abspath(__file__), '_ninja', kdir,
               f'auto{jobs}', 'objs.ninja']
        rc = subprocess.call(cmd)
        if rc:
            # once more for what failed (ninja keeps what built): 2026-10-23, one TU of 1167 failed with clang's
            # "unable to rename temporary....o.tmp to output file: no such file or directory" (the.tmp was there)
            log('game objects: ninja failed, once more for the TUs that did not build')
            rc = subprocess.call(cmd)
    stored = 0
    for obj, src, rule, oid in todo:
        o = os.path.join(kdir, obj)
        # after a failed run only what this run wrote: an older object may be from other source text
        if oid and os.path.exists(o) and (rc == 0 or os.path.getmtime(o) >= t0):
            c = os.path.join(CACHE, oid[:2], oid + '.o')
            os.makedirs(os.path.dirname(c), exist_ok=True)
            try:
                os.link(o, c); stored += 1
            except FileExistsError:
                pass
    if rc:
        sys.exit(f'game objects: ninja failed ({rc}); {stored} objects that did build are in the cache')
    return {'tus': len(edges), 'cached': hits, 'compiled': len(todo), 'minutes': round((time.time() - t0) / 60, 1)}


def prune_cache(days=7):
    """objects no key links any more (a deleted key dir leaves its cache entries with one link) go after `days`"""
    old, n, size = time.time() - days * 86400, 0, 0
    for d, _, files in os.walk(CACHE):
        for fn in files:
            p = os.path.join(d, fn)
            st = os.stat(p)
            if st.st_nlink == 1 and st.st_mtime < old:
                os.remove(p); n += 1
            else:
                size += st.st_size
    log(f'object cache: {size / 1e9:.1f} GB' + (f', {n} unlinked objects older than {days} days removed' if n else ''))


def key_dir(key):
    """<work>/engine/game/<key>, or game-var/<key> for a build variant (--opt/--march/--pgo/--lto/--ref/--gen-args):
    boot.py's default exe and allon.py take the newest key under game/, and a variant must never be picked as the
    `runtime --key` finds a key in either."""
    if VARIANT or gen_variant() or REF:
        return os.path.join(SIG, 'game-var', key)
    for sub in ('game', 'game-var'):
        if os.path.exists(os.path.join(SIG, sub, key, 'manifest.json')):
            return os.path.join(SIG, sub, key)
    return os.path.join(SIG, 'game', key)


def key_files_gone(kdir, man):
    """the dirs a key's manifest says are built but are not there: gen\\main (gen_done), obj (objs_done). A disk
    clean-up took them (2026-10-25 19:44: 8 keys at once) and integration's 8437ba30 then failed at lld-link."""
    return [d for d, flag in ((os.path.join('gen', 'main'), 'gen_done'), ('obj', 'objs_done'))
            if man.get(flag) and not os.path.isdir(os.path.join(kdir, d))]


def cmd_game(a):
    global TOOLS
    TOOLS = snapshot(REF or 'HEAD')
    img = images(a.patches)
    key, parts = key_of(img, TOOLS)
    kdir = key_dir(key)
    os.makedirs(kdir, exist_ok=True)
    log(f'key {key} -> {kdir}')
    if pgo_age(parts):
        log(f'PGO profile {VARIANT["pgo"]}: trained on another {", ".join(pgo_age(parts))}; functions changed since '
            'then compile without profile data (retrain: python tools/engine/pgo_train.py)')
    with Lock(kdir):
        mpath = os.path.join(kdir, 'manifest.json')
        man = json.load(open(mpath)) if os.path.exists(mpath) else {}
        gone = key_files_gone(kdir, man)
        if gone:   # rebuild what is missing instead of trusting the flags
            log(f'{", ".join(gone)} missing although the manifest says built (a disk clean-up): rebuilding')
            man.pop('objs_done', None)
            if os.path.join('gen', 'main') in gone:
                man.pop('gen_done', None)
        if not man.get('objs_done'):
            if not man.get('gen_done'):
                if a.patches and not a.cache and not os.path.exists(os.path.join(kdir, 'build.ninja')):
                    bkey, _ = key_of(images(None), TOOLS)
                    bdir = os.path.join(SIG, 'game', bkey)
                    if json.load(open(os.path.join(bdir, 'manifest.json'))).get('objs_done') if os.path.exists(os.path.join(bdir, 'manifest.json')) else False:
                        log(f'patched key: hard-linking the base key {bkey} (only changed TUs recompile)')
                        clone_links(bdir, kdir)
                twin = None if os.environ.get('NXR_GEN_TWIN') == '0' else gen_twin(parts, kdir)
                if twin:
                    t0 = time.time()
                    link_gen(twin, kdir)
                    log(f'gen: key {os.path.basename(twin)} has the same generated sources (only compile options '
                        f'differ): hard-linked its gen ({time.time() - t0:.0f} s; NXR_GEN_TWIN=0 runs gen.py instead)')
                else:
                    # through heavy.py: 6 gen.py shares + tusplit (~1 GB on main) at once
                    run([sys.executable, HEAVY, '--prio', a.prio, '--', sys.executable, os.path.abspath(__file__), '_gen',
                         img, kdir, TOOLS, str(SPLIT), HOT or '', ' '.join(GEN_EXTRA)])
                man.update(key=key, parts=parts, img=img, patches=a.patches, src=TOOLS, gen_done=True)
                json.dump(man, open(mpath, 'w', newline='\n'), indent=1)
            run([PY, '-I', os.path.join(TOOLS, 'tools', 'recomp', 'mkninja_win.py'), '--game-only', '--root', TOOLS,
                 '--rt-include', rt_include(TOOLS),
                 '--gen', os.path.join(kdir, 'gen', 'main'), '--obj', os.path.join(kdir, 'obj'), '--out', kdir,
                 '--gen-pool', str(a.jobs)])
            t0 = time.time()
            if a.cache or SPLIT or NOLINES or VARIANT:
                man['objs'] = objects(kdir, a.jobs, a.prio, a.cache)
                if a.cache:
                    prune_cache()
            else:
                run([sys.executable, HEAVY, '--prio', a.prio, '--', sys.executable, os.path.abspath(__file__), '_ninja', kdir, str(a.jobs)])
            man.update(objs_done=True, objs_built=time.strftime('%Y-%m-%d %H:%M'), objs_minutes=round((time.time() - t0) / 60, 1))
            json.dump(man, open(mpath, 'w', newline='\n'), indent=1)
        log('game objects ready')
    if not a.no_exe:
        runtime_build(TOOLS, os.path.join(kdir, 'exe'), kdir, a.jobs_rt, *debug_files(a))
    print(json.dumps({'key': key, 'dir': kdir, 'img': img, 'exe': None if a.no_exe else os.path.join(kdir, 'exe', 'totk.exe'),
                      'commit': COMMIT}))



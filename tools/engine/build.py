def main():
    global SPLIT, HOT, NOLINES, REF, GIANT_LINES
    if len(sys.argv) > 1 and sys.argv[1] == '_ninja':
        cmd_ninja(*sys.argv[2:6]); return
    if len(sys.argv) > 1 and sys.argv[1] == '_gen':     # (internal, run by heavy.py) gen of a key directory
        global TOOLS
        img, kdir, TOOLS, split, hot = sys.argv[2:7]
        SPLIT, HOT = int(split), hot or None
        GEN_EXTRA[:] = sys.argv[7].split() if len(sys.argv) > 7 else []
        gen(img, kdir); return
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)

    def split_args(p):
        p.add_argument('--split', type=int, default=SPLIT, metavar='N',
                       help='re-cut the TUs at ~N guest instructions with stable boundaries (tusplit.py); 0 = off')
        p.add_argument('--hot', help='with --split: hot function names (f_<hex>/s_<hex>); the others compile at ' + COLD_OPT)
        p.add_argument('--opt', choices=['-O3'], help='game objects at -O3 instead of -O2')
        p.add_argument('--march', help='instead of x86-64-v3: x86-64-v2 for processors without AVX2 (the Builder\'s '
                       '--cpu v2, rt_x86v2.h force-included), or e.g. znver5 (this PC only, never a shipped package)')
        p.add_argument('--pgo', metavar='gen|FILE.profdata',
                       help='gen: an instrumented key (boots write profiles with TOTK_PGO_DUMP); a .profdata: use it')
        p.add_argument('--lto', choices=['thin'], help='ThinLTO across the game objects (the backends run at link)')
        p.add_argument('--no-line-tables', action='store_true',
                       help='game objects without -gline-tables-only (same code, 1/4 the bytes, ~10%% less compile)')
        p.add_argument('--giant-lines', type=int, default=GIANT_LINES, metavar='N',
                       help=f'TUs whose largest function has N+ lines compile {GIANT_POOL} at a time, first, at '
                            f'{COLD_OPT} unless profiled warm ({sorted(GIANT_HOT)}); 0 = off (the old rule)')
        p.add_argument('--package', action='store_true',
                       help=f'the play package variant {PACKAGE} + --no-line-tables; not with '
                            '--opt/--march/--pgo/--lto')
    def debug_args(p):
        p.add_argument('--pdb', action='store_true', help='link with /DEBUG: totk.pdb (~820 MB); also NXR_ENGINE_PDB=1')
        p.add_argument('--map', action='store_true', help='write totk.exe.map (~47 MB; hostprof.py, hotset.py)')
    g = sub.add_parser('game')
    debug_args(g)
    g.add_argument('--patches'); g.add_argument('--prio', default=os.environ.get('NXR_HEAVY_PRIO', 'normal'))
    g.add_argument('--jobs', type=int, default=GAME_JOBS_MAX,
                   help=f'generated TUs compiled at once (at most GAME_JOBS_MAX = {GAME_JOBS_MAX}, fewer when free '
                        f'commit is short; a median TU ~0.3 GB, a giant ~2.2 GB: {GIANT_POOL} at a time in its own pool)')
    g.add_argument('--jobs-rt', type=int, default=6); g.add_argument('--no-exe', action='store_true')
    g.add_argument('--no-cache', dest='cache', action='store_false',
                   help=f'do not reuse game objects of other keys by content ({CACHE})')
    g.add_argument('--ref', help='build the sources of this commit / branch instead of HEAD (game-var/)')
    g.add_argument('--gen-args', default='', help='extra gen.py flags for both modules, e.g. "--fz" (game-var/)')
    split_args(g)
    r = sub.add_parser('runtime')
    r.add_argument('--root', required=True); r.add_argument('--out', required=True)
    r.add_argument('--patches'); r.add_argument('--key'); r.add_argument('--jobs', type=int, default=6)
    r.add_argument('--strict-patches', action='store_true',
                   help="refuse a key built from a stale patch set (release relinks; default: a warning)")
    r.add_argument('--rt-lto', action='store_true',
                   help='ThinLTO across the runtime TUs (not the game objects; runtime PGO)')
    split_args(r); debug_args(r)
    o = sub.add_parser('overlay'); o.add_argument('--force', action='store_true')
    sub.add_parser('glyphs')
    o = sub.add_parser('overlay-aspect'); o.add_argument('--set', required=True, help='<w>x<h>[-center]')
    k = sub.add_parser('key'); k.add_argument('--patches'); k.add_argument('--root')

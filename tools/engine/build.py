def small_link(out, pdb, mapfile, variant={}, rt_lto=False, root=None):
    """the link rule of <out>/build.ninja without the PDB (821 MB) and the.map (47 MB) unless asked for: a relink
    dir holds the 263 MB exe and nothing else big (2026-10-23: 29 relink dirs took C: under the 40 GB line).
    Without /DEBUG lld-link turns /OPT:REF and /OPT:ICF on, and ICF would fold identical guest functions into one
    address (ftab, the sampler's guest_fn_of); /OPT:NOREF,NOICF keeps the code what it was with /DEBUG."""
    p = os.path.join(out, 'build.ninja')
    text = open(p).read()
    m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if not m or ' -Wl,/DEBUG' not in m.group(0) or ' -Wl,/MAP:$out.map' not in m.group(0):
        sys.exit(f'{p}: no `rule link` with /DEBUG and /MAP to make small (mkninja_win.py changed?)')
    rule = m.group(0)
    run_from = None   # (returned: the directory ninja must run this file from, None for <out>)
    if not pdb:
        rule = rule.replace(' -Wl,/DEBUG', ' -Wl,/OPT:NOREF -Wl,/OPT:NOICF')
    if not mapfile:
        rule = rule.replace(' -Wl,/MAP:$out.map', '')
    # /Brepro: the exe's header timestamp is a hash of its contents, not the link time, so the same objects always link
    # to the same bytes: an update that reused cached objects can be checked against a fresh build by the exe's hash
    # (setup-speed, the v0.1.8 gate). A link flag only: no object, no key changes
    rule = rule.replace(' -fuse-ld=lld', ' -fuse-ld=lld -Wl,/Brepro', 1)
    # The runtime's C++ with _DISABLE_CONSTEXPR_MUTEX_CONSTRUCTOR, here in the relink's own build.ninja (its game
    # objects are prebuilt, so cxxflags is the runtime's alone; mkninja_win.py's lines join the key through gen_rule):
    # since MSVC 14.40 std::mutex's constexpr constructor needs that STL's msvcp140.dll, and a player's older one
    # (a pre-17.10 VC++ redistributable) crashed totk.exe before main (checked with Microsoft's 14.29 DLLs: the
    # define makes mutexes initialise through the DLL, _Mtx_init_in_situ). Microsoft's own workaround.
    mv = re.search(r'^cxxflags = .*$', text, re.M)
    if not mv:
        sys.exit(f'{p}: no cxxflags line for -D_DISABLE_CONSTEXPR_MUTEX_CONSTRUCTOR')
    text = text[:mv.end()] + ' -D_DISABLE_CONSTEXPR_MUTEX_CONSTRUCTOR' + text[mv.end():]
    m = re.search(r'^rule link\n  command = .*$', text, re.M)
    # a variant key's link side: --pgo gen links the profile runtime (clang's driver adds clang_rt.profile) and
    # builds rt_main.cpp's TOTK_PGO_GEN dump thread (the game is killed, so the at-exit write never runs);
    # --lto thin does the ThinLTO backends at link time, cached across relinks
    if variant.get('pgo') == 'gen':
        rule = rule.replace(' -fuse-ld=lld', ' -fuse-ld=lld -fprofile-generate')
        mv = re.search(r'^cxxflags = .*$', text, re.M)
        if not mv:
            sys.exit(f'{p}: no cxxflags line for -DTOTK_PGO_GEN')
        text = text[:mv.end()] + ' -DTOTK_PGO_GEN' + text[mv.end():]
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if variant.get('pgo_rt'):   # the runtime's compiles (cvkflags includes $cflags): instrumented, or with the profile
        use = ('-fprofile-generate' if variant['pgo'] == 'gen' else
               f"-fprofile-use={os.path.join(SIG, 'pgo', variant['pgo'] + '.profdata')}")
        for name in ('cxxflags', 'cflags'):
            mv = re.search(rf'^{name} = .*$', text, re.M)
            if not mv:
                sys.exit(f'{p}: no {name} line for the runtime PGO flags')
            text = text[:mv.end()] + f' {use} {PGO_NAMES}' + text[mv.end():]
        # each runtime source by its path below the root, and ninja run from there (runtime_build): clang names a C++
        # anonymous namespace after the path it is given (?A0x<hash>), so with absolute paths the training's snapshot, a
        # package tree and a Setup install named those functions apart and the profile missed them. Outputs, depfiles
        # and logs stay in <out>
        base = os.path.normcase(os.path.abspath(root or ENGINE)).replace('\\', '/').rstrip('/') + '/'

        def below(mb):
            src = mb.group(3).replace('$:', ':').replace('$ ', ' ')   # (ninja's escapes: a drive's colon, a space)
            if not os.path.normcase(src).replace('\\', '/').startswith(base):
                return mb.group(0)
            return f'build {mb.group(1)}: {mb.group(2)} ' + src[len(base):].replace(' ', '$ ')
        text = re.sub(r'^build ((?:\$[ :]|[^\s:])+): (cxx|c|cvk) ((?:\$ |\S)+)$', below, text, flags=re.M)
        text = f"builddir = {os.path.abspath(out).replace(os.sep, '/').replace('$', '$$')}\n" + text
        run_from = root or ENGINE
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if rt_lto:   # --rt-lto: ThinLTO across the runtime's TUs only (the game objects stay COFF: a short link)
        for name in ('cxxflags', 'cflags'):
            mv = re.search(rf'^{name} = .*$', text, re.M)
            if not mv:
                sys.exit(f'{p}: no {name} line for --rt-lto')
            text = text[:mv.end()] + ' -flto=thin' + text[mv.end():]
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if GAME_VERSION != '1.0.0':  # another game version: totk_version.h's address table
        for name in ('cxxflags', 'cflags'):
            mv = re.search(rf'^{name} = .*$', text, re.M)
            if not mv:
                sys.exit(f'{p}: no {name} line for -DTOTK_GAME_VERSION')
            text = text[:mv.end()] + f" -DTOTK_GAME_VERSION={VERSION_DIR[1:]} -DTOTK_MAIN_SPAN={BUILD_SPAN:#x}ull" + (
                ' -DTOTK_CAP30' if 'cap30' in SAFE_MODE else '') + ''.join(   # (hle_vi.cpp: nothing above 30)
                f' -DTOTK_BETA_OFF_{g.upper()}' for g in BETA.get('off_features', [])) + text[mv.end():]   # (a beta's
                # features off in the exe itself, whatever env / settings.ini say: pc_input.cpp, totk_menu_cursor.cpp,
                # totk_options_menu.cpp)
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if variant.get('march'):   # the runtime at the key's level too: a v2 exe must not carry v3 runtime code
        for name in ('cxxflags', 'cflags'):
            mv = re.search(rf'^{name} = .*$', text, re.M)
            if not mv or '-march=x86-64-v3' not in mv.group(0):
                sys.exit(f'{p}: no {name} line with -march=x86-64-v3 for --march')
            line = mv.group(0).replace('-march=x86-64-v3', f"-march={variant['march']}")
            if no_avx(variant['march']):
                line += ' -include ' + os.path.join(root or ENGINE, 'runtime', 'rt_x86v2.h').replace('\\', '/')
            text = text[:mv.start()] + line + text[mv.end():]
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
        if no_avx(variant['march']):   # without F16C, _Float16 conversions call __extendhfsf2 / __truncsfhf2 (compiler-rt)
            lib = sorted(glob.glob(os.path.join(LLVM, '..', 'lib', 'clang', '*', 'lib', 'windows',
                                                'clang_rt.builtins-x86_64.lib')))
            if not lib:
                sys.exit(f'no clang_rt.builtins-x86_64.lib under {LLVM}\\..\\lib\\clang: an x86-64-v2 key needs it')
            rule = rule.replace(' -fuse-ld=lld', ' -fuse-ld=lld "' + os.path.normpath(lib[-1]).replace('\\', '/') + '"', 1)
    if variant.get('lto') or rt_lto:
        rule = rule.replace(' -fuse-ld=lld', f" -fuse-ld=lld -flto={variant.get('lto') or 'thin'} -Wl,/opt:lldltojobs=6 "
                            f"-Wl,/lldltocache:{os.path.join(SIG, 'ltocache')}")
    if ' -fuse-ld=lld' not in rule:
        sys.exit(f'{p}: `rule link` has no -fuse-ld=lld')
    open(p, 'w', newline='\n').write(text[:m.start()] + rule + text[m.end():])
    # a relink without them removes the ones of an earlier link
    for fn, keep in (('totk.pdb', pdb), ('totk.exe.map', mapfile)):
        if not keep and os.path.exists(os.path.join(out, fn)):
            os.remove(os.path.join(out, fn))
    return run_from


def write_json(path: str, obj) -> None:
    """path written whole or not at all: a.tmp, then os.replace (a killed build or a full disk mid-write left a
    truncated key manifest)"""
    tmp = f'{path}.{os.getpid()}.tmp'
    with open(tmp, 'w', newline='\n') as f:
        json.dump(obj, f, indent=1)
    os.replace(tmp, path)


def source_of(root: str) -> dict:
    """the commit a runtime build's sources are: a snapshot (<SIG>/src/<commit12>/engine) names it (the full hash when
    this run exported it, COMMIT), a worktree's --root its HEAD, marked dirty when engine/ has uncommitted edits;
    commit None outside git"""
    r = os.path.abspath(root)
    snap = os.path.dirname(r)
    if os.path.normcase(os.path.dirname(snap)) == os.path.normcase(os.path.join(SIG, 'src')):
        c12 = os.path.basename(snap)
        return {'commit': COMMIT if COMMIT and COMMIT.startswith(c12) else c12, 'dirty': False}
    head = subprocess.run(['git', '-C', r, 'rev-parse', 'HEAD'], capture_output=True, text=True)
    if head.returncode:
        return {'commit': None, 'dirty': None}
    st = subprocess.run(['git', '-C', r, 'status', '--porcelain', '--', '.'], capture_output=True, text=True)
    return {'commit': head.stdout.strip(), 'dirty': bool(st.stdout.strip())}


def runtime_build(root, out, kdir, jobs, pdb=False, mapfile=False, rt_lto=False):
    man = json.load(open(os.path.join(kdir, 'manifest.json')))
    if not man.get('objs_done'):
        sys.exit(f'{kdir}: game objects not built (python tools/engine/build.py game)')
    gone = key_files_gone(kdir, man)
    if gone:
        sys.exit(f'{kdir}: {", ".join(gone)} deleted although the manifest says built (a disk clean-up): the build.py '
                 f'game command that made key {man.get("key")} rebuilds them (patches: {man.get("patches")})')
    if fsha(os.path.join(root, 'runtime', 'rt.h')) != man['parts']['rt.h']:
        sys.exit(f'{root}/runtime/rt.h differs from the one the shared objects of {man["key"]} were built with: '
                 'rt.h changes need a new game build (python tools/engine/build.py game)')
    stale = key_patches_stale(man)
    if stale:   # a warning for test relinks; a release relink passes --strict-patches (or TOTK_PATCHES_STRICT=1)
        if os.environ.get('TOTK_PATCHES_STRICT') == '1':
            sys.exit(stale)
        print(f'WARNING: {stale}', file=sys.stderr, flush=True)
    os.makedirs(out, exist_ok=True)
    run([PY, '-I', os.path.join(root, 'tools', 'recomp', 'mkninja_win.py'), '--prebuilt-gen', '--root', root,
         '--gen', os.path.join(kdir, 'gen', 'main'), '--obj', os.path.join(kdir, 'obj'), '--out', out, '--vcpkg', VCPKG, *RT_ARGS])
    run_from = small_link(out, pdb, mapfile, json.loads(man['parts'].get('variant', '{}')), rt_lto, root)
    t0 = time.time()
    # through heavy.py: 6 runtime compiles (~0.6 GB each) and lld (~1.2 GB); a failure (memory: see objects()) again
    # with fewer at once, down to one
    ladder = retry_jobs(jobs)
    for i, j in enumerate(ladder):
        if i:
            log(f'runtime + link: it failed; again with fewer compiles at once ({ladder[i - 1]} -> {j}): on a PC short '
                'of memory compiles fail when many run together')
        try:
            run([sys.executable, HEAVY, '--prio', os.environ.get('NXR_HEAVY_PRIO', 'normal'), '--', sys.executable,
                 os.path.abspath(__file__), '_ninja', run_from or out, str(j),
                 os.path.join(os.path.abspath(out), 'build.ninja') if run_from else 'build.ninja', 'stop'])
            break
        except subprocess.CalledProcessError as e:
            if i == len(ladder) - 1:
                sys.exit(f'runtime + link: failed ({e.returncode}) even {j} compile(s) at a time; the lines above name '
                         'the step that failed')
    log(f'runtime + link: {time.time() - t0:.0f} s -> {os.path.join(out, "totk.exe")}')
    # what this exe was built from, next to it: the key manifest's src is the snapshot its game objects were generated
    # from and stays so (canary_engine.py reads that rt.h); a runtime-only relink from a newer tree would otherwise be
    # named after the key's first commit
    src = dict(source_of(root), root=os.path.abspath(root), key=man.get('key'), built=time.strftime('%Y-%m-%d %H:%M'))
    write_json(os.path.join(out, 'source.json'), src)
    return src



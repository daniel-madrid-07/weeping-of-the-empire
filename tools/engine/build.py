def dlss_fetch(files, dst, flat):
    """files {upstream path: sha256} into dst (flat: by base name, else lib/ files as lib/<name>), downloaded once and
    checked; a file already there with the right hash is kept."""
    import urllib.request
    for path, want in files.items():
        name = os.path.basename(path) if flat else (path if not path.startswith('lib/') else 'lib/' + os.path.basename(path))
        out = os.path.join(dst, name)
        if os.path.isfile(out) and sha256_file(out) == want:
            continue
        os.makedirs(os.path.dirname(out), exist_ok=True)
        log(f'DLSS SDK: {DLSS_URL}{path}')
        with urllib.request.urlopen(DLSS_URL + path, timeout=120) as r:
            data = r.read()
        got = hashlib.sha256(data).hexdigest()
        if got != want:
            sys.exit(f'DLSS SDK: {path} has sha256 {got}, expected {want}')
        with open(out + '.tmp', 'wb') as f:
            f.write(data)
        os.replace(out + '.tmp', out)


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def dlss_sdk(third_party):
    """third_party: a snapshot's engine/third_party/dlss, given the SDK when the tree has none; None: the DLLs."""
    if third_party is None:
        dlss_fetch(DLSS_DLLS, os.path.join(SIG, 'dlss'), flat=True)
    elif not os.path.isfile(os.path.join(third_party, 'include', 'nvsdk_ngx_vk.h')):
        dlss_fetch(DLSS_SDK, third_party, flat=False)


def snapshot(ref='HEAD') -> str:
    """HEAD's engine/ exported to <work>/engine/src/<commit>/engine: the shared build never sees anyone's uncommitted edits
    in the shared work tree (2026-10-23: a half-edited exec.c broke the first shared exe). --ref: that commit's."""
    global COMMIT
    c = subprocess.run(['git', '-C', REPO, 'rev-parse', '--verify', ref + '^{commit}'], capture_output=True, text=True,
                       check=True).stdout.strip()
    COMMIT = c
    d = os.path.join(SIG, 'src', c[:12])
    if not os.path.exists(os.path.join(d, 'DONE')):
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(d)
        # engine/runtime/nvn/totk_game_patches.c includes the C from games/totk/ a --ref commit from
        # before a path existed exports without it (git archive refuses unknown paths)
        have = subprocess.run(['git', '-C', REPO, 'ls-tree', '--name-only', c, '--', *SNAPSHOT_PATHS], capture_output=True,
                              text=True, check=True).stdout.split()
        tar = subprocess.run(['git', '-C', REPO, 'archive', '--format=tar', c, *[p for p in SNAPSHOT_PATHS if p in have]],
                             capture_output=True,
                             check=True).stdout
        with tarfile.open(fileobj=io.BytesIO(tar)) as t:
            t.extractall(d)
        dlss_sdk(os.path.join(d, 'engine', 'third_party', 'dlss'))
        open(os.path.join(d, 'DONE'), 'w').close()
    dlss_sdk(None)   # the runtime DLLs: <work>/engine/dlss (boot.py and package.py point TOTK_DLSS_DIR there)
    log(f'sources: {ref} {c[:12]} -> {d}')
    return os.path.join(d, 'engine')


def gen_rule(root: str) -> str:
    """hash of the game objects' compile rule (variables + `rule gen` of a --game-only build.ninja written with a fixed
    rt.h placeholder): a flag change for the runtime alone does not invalidate the shared objects"""
    d = os.path.join(SIG, 'tmp', f'rule-{os.getpid()}')
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(os.path.join(d, 'gen', 'main'))
    subprocess.run([PY, '-I', os.path.join(root, 'tools', 'recomp', 'mkninja_win.py'), '--game-only', '--root', root,
                    '--rt-include', 'RTH', '--gen', os.path.join(d, 'gen', 'main'), '--obj', os.path.join(d, 'obj'), '--out', d],
                   check=True, stdout=subprocess.DEVNULL)
    text = open(os.path.join(d, 'build.ninja')).read()
    shutil.rmtree(d, ignore_errors=True)
    keep = [l for l in text.split('\nbuild ')[0].splitlines() if not l.startswith(('cflags', 'cvkflags', 'cc_', '  depth'))]
    return sha('\n'.join(keep).encode())


def gen_args(base):
    """a module's gen.py arguments: its defaults + --gen-args. --no-lso-abi (build.py's, not gen.py's) drops the default
    --lso-abi auto, an explicit --lso-abi FILE replaces it (gen.py would take the last one), and an explicit
    --lso-abi auto is the default already"""
    extra = [x for x in GEN_EXTRA if x != '--no-lso-abi']
    for k in range(len(extra) - 1):
        if extra[k:k + 2] == ['--lso-abi', 'auto']:
            del extra[k:k + 2]
            break
    a = list(base)
    if '--no-lso-abi' in GEN_EXTRA or '--lso-abi' in extra:
        k = a.index('--lso-abi')
        del a[k:k + 2]
    return a + extra


def gen_variant():
    """--gen-args that change the gen.py arguments (a key under game-var/)"""
    return (gen_args(GEN_MAIN), gen_args(GEN_SDK)) != (GEN_MAIN, GEN_SDK)


def abi_jobs(mod):
    """abi_scan.py's first-pass processes: gen() scans main and sdk at once, so sdk gets ABI_SDK_JOBS and main what the
    free commit carries above ABI_MARGIN_GB, ABI_WORKER_GB a process, up to ABI_MAIN_JOBS"""
    cores = os.cpu_count() or 1
    if mod != 'main':
        return min(ABI_SDK_JOBS, cores)
    fit = int((heavy_mod().free_commit_gb() - ABI_MARGIN_GB - ABI_SDK_JOBS * ABI_WORKER_GB) / ABI_WORKER_GB)
    return max(1, min(ABI_MAIN_JOBS, cores, fit))


def lso_abi_auto(args, mod, fj, img):
    """gen.py --lso-abi auto: engine/tools/recomp/abi_scan.py's keep file for this module's image and funcs.json, made
    once into <img>/abi_keep_<mod>_<hash>.txt (the image directory is shared: written through a temp name)"""
    if '--lso-abi' not in args or args[args.index('--lso-abi') + 1] != 'auto':
        return args
    tool = os.path.join(TOOLS, 'tools', 'recomp', 'abi_scan.py')
    h = sha(''.join(fsha(p) for p in (os.path.join(img, mod + '.bin'), fj, tool,
                                      os.path.join(TOOLS, 'tools', 'recomp', 'gen.py'))).encode())[:16]
    out = os.path.join(img, f'abi_keep_{mod}_{h}.txt')
    if not os.path.exists(out):
        t0 = time.time()
        tmp = f'{out}.{os.getpid()}.tmp'
        run([PY, '-I', tool, os.path.join(img, mod), fj, mod, tmp, '--jobs', str(abi_jobs(mod))],
            stdout=subprocess.DEVNULL)
        os.replace(tmp, out)
        log(f'abi_scan {mod}: {out} ({time.time() - t0:.0f} s)')
    a = list(args)
    a[a.index('--lso-abi') + 1] = f'{out}@{mod}'
    return a


def key_of(img: str, root: str):
    """root = the engine tree whose tools and rt.h make the objects (a HEAD snapshot for `game`, yours for `runtime`)"""
    parts = {
        'main.bin': fsha(os.path.join(img, 'main.bin')),
        'sdk.bin': fsha(os.path.join(img, 'sdk.bin')),
        'gen.py': fsha(os.path.join(root, 'tools', 'recomp', 'gen.py')),
        'funcs.py': fsha(os.path.join(root, 'tools', 'funcs.py')),
        'gen args': sha(repr((gen_args(GEN_MAIN), gen_args(GEN_SDK))).encode()),
        'rt.h': fsha(os.path.join(root, 'runtime', 'rt.h')),
        'gen rule': gen_rule(root),
        'clang': sha(clang_version().encode()),
    }
    if '--lso-abi' in gen_args(GEN_MAIN) + gen_args(GEN_SDK):   # (its keep file follows from the image, funcs.json and these)
        parts['abi_scan.py'] = fsha(os.path.join(root, 'tools', 'recomp', 'abi_scan.py'))
    pset = patch_set(img)
    if pset.get('ext') or pset.get('fde_add'):   # only keys whose patch set has veneers
        parts['gen_ext.py'] = fsha(os.path.join(root, 'tools', 'recomp', 'gen_ext.py'))
        # (the veneers are not in the image, so their metadata joins the key itself)
        parts['veneers'] = sha(json.dumps({'ext': pset.get('ext', {}), 'fde_add': pset.get('fde_add', {})}, sort_keys=True).encode())
    if NOLINES:
        parts['objs'] = 'no line tables'
    if VARIANT:
        parts['variant'] = json.dumps(VARIANT, sort_keys=True)
    if REF:   # (the exe's runtime comes from the ref too, and two refs can share gen.py and rt.h)
        parts['ref'] = os.path.basename(os.path.dirname(root))
    if SPLIT:
        parts['split'] = sha(repr((SPLIT, fsha(tusplit.__file__), fsha(genshard.__file__), fsha(HOT) if HOT else None,
                                   COLD_OPT)).encode())
    if GIANT_LINES:   # (the pool depth changes no object)
        parts['giants'] = repr((GIANT_LINES, sorted(GIANT_HOT), COLD_OPT))
    return sha(json.dumps(parts, sort_keys=True).encode())[:16], parts



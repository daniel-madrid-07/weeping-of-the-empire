"""Build the engine (totk-recomp, `engine/`) on Windows, with game objects shared between builds and worktrees.

The game objects (gen.py's 214 TUs, ~45 min) are built once per key into <work>/engine/game/<key>/. A runtime change
(anything under engine/runtime except rt.h) relinks against them in minutes. Nobody runs a private full build.

usage:
  python tools/engine/build.py game    [--patches FILE] [--prio normal] [--jobs 6] [--no-exe] [--no-cache] [--split N]
                                       [--ref REF] [--gen-args "--fz"]
        images -> (patch set) -> funcs.py + gen.py (write-if-changed) -> game objects through heavy.py -> an exe of the
        repo's engine/ runtime in <work>/engine/game/<key>/exe/totk.exe. Usually 2-3 min (a key whose TUs are mostly in
        the cache); a cold one ~25 min: start it detached.
        --ref: the sources of a commit or branch instead of HEAD (an unmerged branch's A/B build); --gen-args: extra
        gen.py flags for both modules (its default-off codegen options; GEN_CODEGEN are on already; --no-lso-abi drops
        the default --lso-abi auto). Both join the key and build in game-var/.
        objects by content in <work>/engine/objcache/, shared by every key: a TU whose text, compile rule and toolchain
        match an object built for any key is linked, not compiled (--no-cache: the old per-key ninja build).
        --split N (default 15000; 0 = gen.py's own 60000-instruction cut): tools/engine/tusplit.py re-cuts gen.py's TUs
        at ~N guest instructions with boundaries that stay put when a function changes, so a patch set recompiles only
        the TUs of the functions it touches; gen.py runs in shares at once. --hot F (tools/engine/hotset.py from a
        TOTK_PROF boot): the other functions at -O1. Both join the key.
  python tools/engine/build.py runtime --root <your engine/ tree> --out <dir> [--patches FILE | --key KEY] [--jobs 6]
        runtime-only: compile <root>/runtime and link against the shared objects of the key -> <out>/totk.exe
  python tools/engine/build.py overlay [--force]   romfs overlays (rstb slack, game-over fix, quick-menu fix) and the
                                                    glyph bank on them (glyphs/engine+glyphs)
  python tools/engine/build.py glyphs              the glyph bank alone, on the overlay as it is
  python tools/engine/build.py key     [--patches FILE] [--root DIR]   print the key and what it is made of

Key = sha256 over: the decompressed main and sdk images (after the patch set), gen.py, funcs.py, the gen arguments,
<root>/runtime/rt.h (the only header the generated TUs include), the game objects' compile rule and the clang
version (+ a veneer set's metadata, + the --split parameters). Without --cache a patched key starts as hard links to
its unpatched base, and gen.py's output is written only where it changed, so ninja recompiles only the TUs a patch
touches (with gen.py's own 60000-instruction cut, every TU after a function that changed size).

Patch set: JSON {"name": "...", "patches": [{"module": "main", "offset": "0x7a83e4", "bytes": "1f2003d5", "expect": "..."}]}
offset = byte offset in the decompressed image (guest address - module base); expect (optional) = the bytes there before
patching, checked. Optional "fde_add" {"0x<start>": size} and "ext" {"0x<function>": [["0x<a>", "0x<b>"]]}: game patches'
veneers (functions to add, code outside a function's FDE that belongs to it); a set with them is generated by
engine/tools/recomp/gen_ext.py, which joins its key. The `python -m games.totk.patches` writes such sets.

Layout under <work>/engine/ (game-derived, never in git):
  venv/                         python with capstone 5.0.9, lz4, ninja (made on first use)
  img/<exefs>[-p<patch>]/       nso.py output: main/sdk/rtld/subsdk0 .bin + .json (TOTK_IMG for boots)
  game/<key>/                   manifest.json, gen/{main,sdk}/*.cpp, funcs_*.json, obj/{gen,sdk}/*.o, build.ninja, exe/
                                (objs.ninja: the objects --cache / --split still compile)
  objcache/<id[:2]>/<id>.o      game objects by content; the keys' obj/ files are hard links to them (an object no
                                key links any more goes after 7 days)
  overlay/romfs/                TOTK_OVERLAY for boots
  glyphs/engine+glyphs/         the glyph bank (TOTK_GLYPHS_DIR default: <overlay>/../../glyphs)
"""

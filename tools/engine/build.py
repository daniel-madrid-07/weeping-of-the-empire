def stale_features(pset: dict) -> list:
    """Each feature whose words in an exported patch set differ from games/totk/patches/v100.toml now (what an export
    today would write: the rows whose new word differs from the original)."""
    import tomllib
    with open(PATCH_TABLE, 'rb') as f:
        table = tomllib.load(f)
    # The table holds no word of the game: a row is our new word, or copy_of (the image's own word moved into a veneer,
    # compared by offset alone); a copy of a word onto itself is a checked guard, not a change (not in the export).
    feats = set(pset.get('features', []))
    want, have = {}, {}
    for r in table.get('patch', []):
        if r['feature'] in feats and r.get('copy_of', -1) != r['offset']:
            want.setdefault(r['feature'], set()).add((r['offset'], r['new'].lower() if 'new' in r else 'copy'))
    copies = {(r['feature'], r['offset']) for r in table.get('patch', []) if 'copy_of' in r}
    for p in pset['patches']:
        name, off = p.get('name', '?'), int(str(p['offset']), 0)
        if name.startswith('mod:'):   # (a player's mod patch, tools/engine/mods_exefs.py: not in the table)
            continue
        have.setdefault(name, set()).add((off, 'copy' if (name, off) in copies else p['bytes'].lower()))
    out = []
    for name in sorted(set(want) | set(have)):
        w, h = want.get(name, set()), have.get(name, set())
        if w != h:
            out.append(f'{name} has {len(h)} words, the table {len(w)} ({len(w - h)} missing, {len(h - w)} not in it)')
    return out


def key_patches_stale(man: dict):
    """A built key's own patch set (<img>/patches.json, the manifest's img) checked against v100.toml now: None when
    current (or unpatched), else the message. A key built from an older export keeps its old words under the same
    feature names, and a runtime relinked on it later would ship them: the key build's check (images) has long
    passed by then."""
    p = os.path.join(man.get('img') or '', 'patches.json')
    try:
        with open(p) as f:
            pset = json.load(f)
    except (OSError, ValueError):
        return None
    if not pset.get('patches'):
        return None
    stale = stale_features(pset)
    if not stale:
        return None
    return (f"key {man.get('key')} was built from a stale patch set ({man.get('patches')}): " + '; '.join(stale)
            + '. A runtime linked on it carries the old words under the same feature names (E14): build the key again '
              'from a fresh export (python -m games.totk.patches engine ...)')


def images(patch_file=None) -> str:
    """decompressed images (+ patch set) -> their directory"""
    ensure_venv()
    ex = sha(b''.join(fsha(os.path.join(EXEFS, m)).encode() for m in MODULES))[:12]
    base = os.path.join(SIG, 'img', ex)
    if not os.path.exists(os.path.join(base, 'DONE')):
        tmp = base + '.tmp'
        shutil.rmtree(tmp, ignore_errors=True)
        os.makedirs(tmp)
        for m in MODULES:
            run([PY, '-I', os.path.join(TOOLS, 'tools', 'nso.py'), os.path.join(EXEFS, m), os.path.join(tmp, m)],
                stdout=subprocess.DEVNULL)
        bid = json.load(open(os.path.join(tmp, 'main.json')))['build_id'][:16].upper()
        if bid != BUILD_ID:
            sys.exit(f'main build id {bid}, expected {BUILD_ID} (TotK {GAME_VERSION})')
        open(os.path.join(tmp, 'DONE'), 'w').close()
        shutil.rmtree(base, ignore_errors=True)
        os.replace(tmp, base)
    if not patch_file:
        return base
    pset = json.load(open(patch_file))
    hooked = HOOKED_V100 if HOOKED_V100 is not None else \
        {h for i, arg in enumerate(GEN_MAIN[:-1]) if arg == '--hook' for h in GEN_MAIN[i + 1].split(',')}
    missing = [h for h in pset.get('hooks', []) if h not in hooked]
    if 'cap30' in SAFE_MODE and 'fps60' in pset.get('features', []):   # hooks that keep >30 fps right were dropped
        sys.exit(f"patch set {pset.get('name', '?')} has fps60, but {GAME_VERSION} lost hooks that keep a frame rate "
                 f"above 30 right ({VERSION_DIR}.engine.json dropped_hooks): export it with --features default,-fps60")
    if 'cap30' in SAFE_MODE and not {'TOTK_LOAD_FPS', 'TOTK_TITLE_FPS', 'TOTK_FPS', 'TOTK_UNLOCK_FPS'} <= set(pset.get('runtime_env') or {}):
        sys.exit(f"patch set {pset.get('name', '?')} lacks the 30 fps runtime_env {GAME_VERSION} needs (TOTK_LOAD_FPS=0, "
                 f"TOTK_TITLE_FPS=0): re-export it (python -m games.totk.patches engine --table {VERSION_DIR}.toml)")
    if missing:   # games/totk/patches/engine.py HOOKS_NEEDED: patched code that needs an engine hook
        sys.exit(f"patch set {pset.get('name', '?')} needs --hook {','.join(missing)} in GEN_MAIN")
    stale = stale_features(pset)
    if stale:
        msg = (f"patch set {pset.get('name', '?')} ({patch_file}) is a stale export: "
               + '; '.join(stale) + ". Re-export it (python -m games.totk.patches engine ...)")
        if os.environ.get('TOTK_PATCHES_STALE_OK') != '1':
            sys.exit(msg + ', or TOTK_PATCHES_STALE_OK=1 for a deliberate diagnostic set')
        log('WARNING: ' + msg + ' (TOTK_PATCHES_STALE_OK=1: built anyway)')
    pdir =f'{base}-p{sha(json.dumps(pset, sort_keys=True).encode())[:12]}'
    if os.path.exists(os.path.join(pdir, 'DONE')):
        return pdir
    tmp = pdir + '.tmp'
    shutil.rmtree(tmp, ignore_errors=True)
    shutil.copytree(base, tmp)
    bins = {}
    for p in pset['patches']:
        mod = p.get('module', 'main')
        b = bins.setdefault(mod, bytearray(open(os.path.join(tmp, mod + '.bin'), 'rb').read()))
        off, new = int(str(p['offset']), 0), bytes.fromhex(p['bytes'])
        if off + len(new) > len(b):   # a veneer in the extra area past the image's end (sites_v100 Layout.extra): zeros
            b += bytes(off + len(new) - len(b))
        if 'expect' in p and b[off:off + len(new)] != bytes.fromhex(p['expect']):
            sys.exit(f"patch {p.get('name', '?')}: {mod}+{off:#x} is {b[off:off + len(new)].hex()}, expected {p['expect']}")
        b[off:off + len(new)] = new
    for mod, b in bins.items():
        open(os.path.join(tmp, mod + '.bin'), 'wb').write(b)
    json.dump(pset, open(os.path.join(tmp, 'patches.json'), 'w', newline='\n'), indent=1)
    shutil.rmtree(pdir, ignore_errors=True)
    os.replace(tmp, pdir)
    return pdir



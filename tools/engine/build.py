def small_link(out, pdb, mapfile, variant={}, rt_lto=False):
    """the link rule of <out>/build.ninja without the PDB (821 MB) and the .map (47 MB) unless asked for: a relink
    dir holds the 263 MB exe and nothing else big (2026-10-23: 29 relink dirs took C: under the 40 GB line).
    Without /DEBUG lld-link turns /OPT:REF and /OPT:ICF on, and ICF would fold identical guest functions into one
    address (ftab, the sampler's guest_fn_of); /OPT:NOREF,NOICF keeps the code what it was with /DEBUG."""
    p = os.path.join(out, 'build.ninja')
    text = open(p).read()
    m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if not m or ' -Wl,/DEBUG' not in m.group(0) or ' -Wl,/MAP:$out.map' not in m.group(0):
        sys.exit(f'{p}: no `rule link` with /DEBUG and /MAP to make small (mkninja_win.py changed?)')
    rule = m.group(0)
    if not pdb:
        rule = rule.replace(' -Wl,/DEBUG', ' -Wl,/OPT:NOREF -Wl,/OPT:NOICF')
    if not mapfile:
        rule = rule.replace(' -Wl,/MAP:$out.map', '')
    # a variant key's link side: --pgo gen links the profile runtime (clang's driver adds clang_rt.profile) and
    # builds rt_main.cpp's TOTK_PGO_GEN dump thread (the game is killed, so the at-exit write never runs);
    # --lto thin does the ThinLTO backends at link time, cached across relinks
    if variant.get('pgo') == 'gen':
        rule = rule.replace(' -fuse-ld=lld', ' -fuse-ld=lld -fprofile-generate')
        mv = re.search(r'^cxxflags = .*$', text, re.M)
        if not mv:
            sys.exit(f'{p}: no cxxflags line for -DTOTK_PGO_GEN')
        text = text[:mv.end()] + ' -DTOTK_PGO_GEN' + text[mv.end():]
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if variant.get('pgo_rt'):   # the runtime's compiles (cvkflags includes $cflags): instrumented, or with the profile
        use = ('-fprofile-generate' if variant['pgo'] == 'gen' else
               f"-fprofile-use={os.path.join(SIG, 'pgo', variant['pgo'] + '.profdata')}")
        for name in ('cxxflags', 'cflags'):
            mv = re.search(rf'^{name} = .*$', text, re.M)
            if not mv:
                sys.exit(f'{p}: no {name} line for the runtime PGO flags')
            text = text[:mv.end()] + f' {use} {PGO_NAMES}' + text[mv.end():]
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if rt_lto:   # --rt-lto: ThinLTO across the runtime's TUs only (the game objects stay COFF: a short link)
        for name in ('cxxflags', 'cflags'):
            mv = re.search(rf'^{name} = .*$', text, re.M)
            if not mv:
                sys.exit(f'{p}: no {name} line for --rt-lto')
            text = text[:mv.end()] + ' -flto=thin' + text[mv.end():]
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if GAME_VERSION != '1.0.0':  # another game version: totk_version.h's address table
        for name in ('cxxflags', 'cflags'):
            mv = re.search(rf'^{name} = .*$', text, re.M)
            if not mv:
                sys.exit(f'{p}: no {name} line for -DTOTK_GAME_VERSION')
            text = text[:mv.end()] + f" -DTOTK_GAME_VERSION={VERSION_DIR[1:]}" + (
                ' -DTOTK_CAP30' if 'cap30' in SAFE_MODE else '') + text[mv.end():]   # (hle_vi.cpp: nothing above 30)
        m = re.search(r'^rule link\n  command = .*$', text, re.M)
    if variant.get('lto') or rt_lto:
        rule = rule.replace(' -fuse-ld=lld', f" -fuse-ld=lld -flto={variant.get('lto') or 'thin'} -Wl,/opt:lldltojobs=6 "
                            f"-Wl,/lldltocache:{os.path.join(SIG, 'ltocache')}")
    if ' -fuse-ld=lld' not in rule:
        sys.exit(f'{p}: `rule link` has no -fuse-ld=lld')
    open(p, 'w', newline='\n').write(text[:m.start()] + rule + text[m.end():])
    # a relink without them removes the ones of an earlier link
    for fn, keep in (('totk.pdb', pdb), ('totk.exe.map', mapfile)):
        if not keep and os.path.exists(os.path.join(out, fn)):
            os.remove(os.path.join(out, fn))


def runtime_build(root, out, kdir, jobs, pdb=False, mapfile=False, rt_lto=False):
    man = json.load(open(os.path.join(kdir, 'manifest.json')))
    if not man.get('objs_done'):
        sys.exit(f'{kdir}: game objects not built (python tools/engine/build.py game)')
    gone = key_files_gone(kdir, man)
    if gone:
        sys.exit(f'{kdir}: {", ".join(gone)} deleted although the manifest says built (a disk clean-up): the build.py '
                 f'game command that made key {man.get("key")} rebuilds them (patches: {man.get("patches")})')
    if fsha(os.path.join(root, 'runtime', 'rt.h')) != man['parts']['rt.h']:
        sys.exit(f'{root}/runtime/rt.h differs from the one the shared objects of {man["key"]} were built with: '
                 'rt.h changes need a new game build (python tools/engine/build.py game)')
    stale = key_patches_stale(man)
    if stale:   # a warning for test relinks; a release relink passes --strict-patches (or TOTK_PATCHES_STRICT=1)
        if os.environ.get('TOTK_PATCHES_STRICT') == '1':
            sys.exit(stale)
        print(f'WARNING: {stale}', file=sys.stderr, flush=True)
    os.makedirs(out, exist_ok=True)
    run([PY, '-I', os.path.join(root, 'tools', 'recomp', 'mkninja_win.py'), '--prebuilt-gen', '--root', root,
         '--gen', os.path.join(kdir, 'gen', 'main'), '--obj', os.path.join(kdir, 'obj'), '--out', out, '--vcpkg', VCPKG])
    small_link(out, pdb, mapfile, json.loads(man['parts'].get('variant', '{}')), rt_lto)
    t0 = time.time()
    # through heavy.py: 6 runtime compiles (~0.6 GB each) and lld (~1.2 GB)
    run([sys.executable, HEAVY, '--prio', os.environ.get('NXR_HEAVY_PRIO', 'normal'), '--', sys.executable,
         os.path.abspath(__file__), '_ninja', out, str(jobs), 'build.ninja', 'stop'])
    log(f'runtime + link: {time.time() - t0:.0f} s -> {os.path.join(out, "totk.exe")}')


def debug_files(a):
    """(pdb, map): --pdb / --map, or NXR_ENGINE_PDB=1 for both (debugging a crash; the sampler's RVAs and
    hotset.py need only the map)"""
    env = os.environ.get('NXR_ENGINE_PDB') == '1'
    return a.pdb or env, a.map or env


def cmd_runtime(a):
    ensure_venv()
    if a.strict_patches:
        os.environ['TOTK_PATCHES_STRICT'] = '1'
    root = os.path.abspath(a.root)
    if a.key:
        kdir = key_dir(a.key)
    else:
        global TOOLS
        TOOLS = root
        key, _ = key_of(images(a.patches), root)
        kdir = key_dir(key)
        if not os.path.exists(os.path.join(kdir, 'manifest.json')):
            sys.exit(f'no shared game objects for key {key} (rt.h, gen tools or patches differ from every built key; '
                     f'built: {", ".join(os.listdir(os.path.join(SIG, "game"))) if os.path.isdir(os.path.join(SIG, "game")) else "none"})')
    runtime_build(root, os.path.abspath(a.out), kdir, a.jobs, *debug_files(a), rt_lto=a.rt_lto)


def cmd_overlay(a):
    ensure_venv()
    out = os.path.join(SIG, 'overlay', 'romfs')
    if os.path.exists(os.path.join(SIG, 'overlay', 'DONE')) and not a.force:
        log(f'{out} exists (--force rebuilds)'); return
    # the engine's own files go to a fresh base each time: the romfs itself already holds the last mals merge, which
    # engine_dir would refuse as the engine's ("ships its own version") on every --force after the first
    base = out + '.base'
    shutil.rmtree(base, ignore_errors=True)
    env = dict(os.environ, TOTK_ROMFS=ROMFS, TOTK_OVERLAY_OUT=base)
    # The three engine fixes, "Skip the opening" and the message texts (games/totk/overlays/mals.py: every message
    # edit, e.g. The Options screen's PC rows; merged into the romfs below by engine_dir, manifest-checked, RSTB
    # raised for the grown Mals archives) write different files: all at once
    jobs = [lambda s=s: run([PY, '-I', os.path.join(ENGINE, 'tools', s)], env=env)
            for s in ('rstb_slack.py', 'make_gameover_fix.py', 'make_quickmenu_fix.py')]
    jobs.append(lambda: run([sys.executable, '-m', 'games.totk.overlays', '--romfs', os.path.dirname(ROMFS), '--out',
                             os.path.join(SIG, 'overlay'), '--only-skip-opening'], cwd=REPO))
    jobs.append(lambda: run([sys.executable, '-m', 'games.totk.overlays.mals', '--romfs', os.path.dirname(ROMFS),
                             '--out', os.path.join(SIG, 'overlay')], cwd=REPO))
    with ThreadPoolExecutor(len(jobs)) as ex:
        for f in [ex.submit(j) for j in jobs]:
            f.result()
    shutil.rmtree(out + '.pc', ignore_errors=True)
    run([sys.executable, '-m', 'games.totk.overlays.engine_dir', '--romfs', os.path.dirname(ROMFS), '--sets', 'mals',
         '--sets-root', os.path.join(SIG, 'overlay'), '--engine', base, '--out', out + '.pc'], cwd=REPO)
    shutil.rmtree(base, ignore_errors=True)
    # (renamed away whole, not deleted file by file: a file a running game holds would stop rmtree half-way and leave
    # every boot without an overlay; a failed rename leaves the old one in place)
    shutil.rmtree(out + '.old', ignore_errors=True)
    try:
        if os.path.exists(out):   # (none yet on a new work folder: tools/builder's first run)
            os.rename(out, out + '.old')
    except OSError as e:
        sys.exit(f'{out} is in use ({e}): {out}.pc is built; run again with no game running (heavy.py --pool gpu --exclusive)')
    os.rename(out + '.pc', out)
    shutil.rmtree(out + '.old', ignore_errors=True)
    def aspect(size):
        aspect_overlay(out, size)
        if os.path.isdir(f'{out}-aspect-{size}'):   # (aspect_overlay logs its own failure and leaves no dir)
            glyph_bank(f'{out}-aspect-{size}', f'engine+glyphs@aspect-{size}')
    with ThreadPoolExecutor(3) as ex:   # (the 16:9 bank and each aspect overlay + its bank: different dirs)
        for f in [ex.submit(glyph_bank, out)] + [ex.submit(aspect, size) for size in ('3440x1440', '5120x1440')]:
            f.result()
    open(os.path.join(SIG, 'overlay', 'DONE'), 'w').close()


def aspect_overlay(romfs, size):
    """graphics.aspect_ratio: the overlay again with the UI layouts for a
    <size> canvas, romfs-aspect-<size> beside romfs (totk_engine_boot points TOTK_OVERLAY at it for a window of that shape).
    From the aspect set in <work>/overlays (python -m games.totk.overlays); one not built there is skipped, and that shape
    keeps the game's 16:9. Not fatal. When it is not rebuilt, the last build goes too (with its glyph bank): it holds an
    older engine overlay (Options rows, sets), which a window of that shape would otherwise still get."""
    name, sets = f'aspect-{size}', os.path.join(WORK, 'overlays')
    dst = f'{romfs}-{name}'
    if not os.path.isdir(os.path.join(sets, name)):
        log(f'WARNING: {dst} not built: no {name} set in {sets} (python -m games.totk.overlays --romfs '
            f'{os.path.dirname(ROMFS)} --out {sets} --aspects {size}); a {size} window keeps the game\'s 16:9')
        drop_aspect_overlay(dst, size)
        return
    shutil.rmtree(dst + '.pc', ignore_errors=True)
    try:
        run([sys.executable, '-m', 'games.totk.overlays.engine_dir', '--romfs', os.path.dirname(ROMFS), '--sets', name,
             '--sets-root', sets, '--engine', romfs, '--out', dst + '.pc'], cwd=REPO)
        shutil.rmtree(dst + '.old', ignore_errors=True)
        if os.path.exists(dst):
            os.rename(dst, dst + '.old')   # (fails whole while a running game holds a file of it)
        os.rename(dst + '.pc', dst)
        shutil.rmtree(dst + '.old', ignore_errors=True)
    except (subprocess.CalledProcessError, OSError) as e:
        log(f'WARNING: {dst} NOT rebuilt ({e}): a {size} window keeps the game\'s 16:9')
        shutil.rmtree(dst + '.pc', ignore_errors=True)
        drop_aspect_overlay(dst, size)


def drop_aspect_overlay(dst, size):
    """A romfs-aspect-<size> left from an earlier overlay build, and its glyph bank, removed (renamed away whole first:
    a running game holding a file of it keeps it, said loudly)."""
    bank = os.path.join(SIG, 'glyphs', f'engine+glyphs@aspect-{size}')
    for d in (dst, bank):
        if not os.path.exists(d):
            continue
        try:
            shutil.rmtree(d + '.old', ignore_errors=True)
            os.rename(d, d + '.old')
            shutil.rmtree(d + '.old', ignore_errors=True)
            log(f'{d}: removed (an earlier build, older than this overlay)')
        except OSError as e:
            log(f'WARNING: {d} is from an EARLIER overlay build and could not be removed ({e}): a {size} window gets '
                f'that older overlay until it is (run again with no game running)')


def glyph_bank(overlay, name='engine+glyphs'):
    """The glyph bank on this overlay's Common archive and resource size table:
    the engine skips a bank whose base.fnv names another overlay, and every button prompt goes back to the game's own,
    so it is rebuilt with the overlay. An aspect overlay (romfs-aspect-<size>, graphics.aspect_ratio) has its own Common
    archive, so its own bank, engine+glyphs@aspect-<size>, which hle_fs.cpp picks for that overlay. Not fatal: without it
    the game shows its own prompts."""
    bank = os.path.join(SIG, 'glyphs', name)
    py = glyph_python()
    if not py:
        log('WARNING: glyph bank NOT rebuilt: no Python here has its packages (PIL, fontTools, skia-pathops, numpy, '
            "zstandard); every button prompt is the game's own until `python tools/engine/build.py glyphs` runs with one")
        return
    try:
        shutil.rmtree(bank + '.new', ignore_errors=True)
        run([py, '-m', 'games.totk.glyphs', '--romfs', os.path.dirname(ROMFS),
             '--art', os.path.join(REPO, 'games', 'totk', 'glyphs', 'kenney'), '--bank', bank + '.new',   # (CC0, its Vector SVGs)
             '--common', os.path.join(overlay, 'UI', 'LayoutArchive', 'Common.Product.100.Nin_NX_NVN.blarc.zs')], cwd=REPO)
        shutil.rmtree(bank + '.old', ignore_errors=True)
        if os.path.exists(bank):
            os.rename(bank, bank + '.old')   # (fails whole while a running game holds a file of it)
        os.rename(bank + '.new', bank)
        shutil.rmtree(bank + '.old', ignore_errors=True)
    except (subprocess.CalledProcessError, OSError) as e:
        log(f'WARNING: glyph bank NOT rebuilt ({e}): the game shows its own button prompts until '
            f'python tools/engine/build.py glyphs runs again')


def glyph_banks(romfs):
    """`build.py glyphs`: the 16:9 overlay's bank and each aspect overlay's that exists"""
    glyph_bank(romfs)
    for size in ('3440x1440', '5120x1440'):
        if os.path.isdir(f'{romfs}-aspect-{size}'):
            glyph_bank(f'{romfs}-aspect-{size}', f'engine+glyphs@aspect-{size}')


@functools.lru_cache(maxsize=1)   # (asked once per run: the overlay's banks build at once)
def glyph_python():
    """A Python with the glyph bank's packages: this one, else `python` / `py -3` on PATH (the venv lacks PIL)."""
    probe = 'import PIL, fontTools, pathops, numpy, zstandard'
    for cand in ([sys.executable], [shutil.which('python')], [shutil.which('py'), '-3']):
        if not cand[0]:
            continue
        try:
            if subprocess.run([*cand, '-c', probe], capture_output=True, timeout=60).returncode == 0:
                if cand[0] != sys.executable:
                    exe = subprocess.run([*cand, '-c', 'import sys; print(sys.executable)'], capture_output=True,
                                         text=True, timeout=60).stdout.strip()
                    log(f'glyph bank: {sys.executable} lacks its packages; using {exe}')
                    return exe or cand[0]
                return cand[0]
        except (OSError, subprocess.TimeoutExpired):
            pass
    return None


